#include "../../chard.h"

void emit_x86_load_scratch(FILE *out, const operand_t *o) {
    int sz = operand_mem_size(o);
    char addr[64];
    x86_addr_text(out, o, addr, sizeof(addr));
    if (sz == 1) fprintf(out, "    movzx %s, byte [%s]\n", SCRATCH_X86, addr);
    else if (sz == 2) fprintf(out, "    movzx %s, word [%s]\n", SCRATCH_X86, addr);
    else if (sz == 4) fprintf(out, "    mov %sd, dword [%s]\n", SCRATCH_X86, addr); /* zero-extends to 64-bit */
    else fprintf(out, "    mov %s, [%s]\n", SCRATCH_X86, addr);
}

void emit_x86_string_bytes(FILE *out, const char *s, int len) {
    for (int i = 0; i < len; i++) {
        fprintf(out, "%s%d", i == 0 ? "" : ", ", (unsigned char)s[i]);
    }
    if (len == 0) fprintf(out, "0"); /* NASM db needs at least one value */
}

void x86_emit_int_val(FILE *out, long val, const int *is_label, char *const *val_labels, int v, int first) {
    fprintf(out, "%s", first ? "" : ", ");
    if (is_label && is_label[v]) fprintf(out, "%s", val_labels[v]);
    else fprintf(out, "%ld", val);
}

void emit_x86_64(FILE *out) {
    fprintf(out, "; Generated by Chard - target: x86-64\n");
    fprintf(out, "; NASM syntax\n");
    fprintf(out, g_mode == MODE_BARE
        ? "; mode: bare (raw/freestanding -- no ELF linkage scaffolding emitted)\n\n"
        : "; mode: elf (Linux)\n\n");

    fprintf(out, "section .data\n");
    for (int i = 0; i < ndecls; i++) {
        if (decls[i].section == SEC_DATA) {
            if (decls[i].is_data_array) {
                const char *dsz = decls[i].size_bytes == 1 ? "db" :
                                   decls[i].size_bytes == 2 ? "dw" :
                                   decls[i].size_bytes == 4 ? "dd" : "dq";
                fprintf(out, "    %s: %s ", decls[i].name, dsz);
                if (decls[i].is_float) {
                    /* Each element emitted as its raw IEEE-754 bit
                       pattern, exactly the way a scalar float decl
                       already is (see double__bits/float__bits above),
                       just looped over data_fvals instead of applied to
                       a single init_fvalue. */
                    for (int v = 0; v < decls[i].array_len; v++) {
                        if (decls[i].size_bytes == 4)
                            fprintf(out, "%s0x%08x", v == 0 ? "" : ", ", float__bits(decls[i].data_fvals[v]));
                        else
                            fprintf(out, "%s0x%016llx", v == 0 ? "" : ", ", (unsigned long long)double__bits(decls[i].data_fvals[v]));
                    }
                } else {
                    for (int v = 0; v < decls[i].array_len; v++)
                        x86_emit_int_val(out, decls[i].data_vals[v], decls[i].data_val_is_label, decls[i].data_val_labels, v, v == 0);
                }
                fprintf(out, "\n");
            } else if (decls[i].is_ascii) {
                fprintf(out, "    %s: db ", decls[i].name);
                emit_x86_string_bytes(out, decls[i].str_val, decls[i].str_len);
                fprintf(out, "\n    %s_len: dq %d\n", decls[i].name, decls[i].str_len);
            } else if (decls[i].is_float) {
                /* Emitted as the raw IEEE-754 bit pattern via dd/dq --
                   see double__bits/float__bits above for why. */
                if (decls[i].size_bytes == 4)
                    fprintf(out, "    %s: dd 0x%08x\n", decls[i].name, float__bits(decls[i].init_fvalue));
                else
                    fprintf(out, "    %s: dq 0x%016llx\n", decls[i].name, (unsigned long long)double__bits(decls[i].init_fvalue));
            } else {
                const char *dsz = decls[i].size_bytes == 1 ? "db" :
                                   decls[i].size_bytes == 2 ? "dw" :
                                   decls[i].size_bytes == 4 ? "dd" : "dq";
                fprintf(out, "    %s: %s %ld\n", decls[i].name, dsz, decls[i].init_value);
            }
        }
    }
    /* 'rodata' -- same per-decl-kind emission as '.data' above (data
       array / ascii / float / plain scalar), just written into
       '.rodata' instead so NASM (and, downstream, the linker) places
       it in a read-only, non-writable section rather than '.data's
       ordinary writable one -- see SEC_RODATA's declaration and the
       'rodata' keyword's comment in parse__decl for the full
       rationale. Emitted as its own loop/section (not folded into the
       '.data' loop above with an extra section_t check per line)
       purely to keep the two sections' contents visibly separate in
       the generated .s file, the same reason '.bss' already gets its
       own loop instead of being interleaved with '.data'. */
    fprintf(out, "\nsection .rodata\n");
    for (int i = 0; i < ndecls; i++) {
        if (decls[i].section == SEC_RODATA) {
            if (decls[i].is_data_array) {
                const char *dsz = decls[i].size_bytes == 1 ? "db" :
                                   decls[i].size_bytes == 2 ? "dw" :
                                   decls[i].size_bytes == 4 ? "dd" : "dq";
                fprintf(out, "    %s: %s ", decls[i].name, dsz);
                if (decls[i].is_float) {
                    for (int v = 0; v < decls[i].array_len; v++) {
                        if (decls[i].size_bytes == 4)
                            fprintf(out, "%s0x%08x", v == 0 ? "" : ", ", float__bits(decls[i].data_fvals[v]));
                        else
                            fprintf(out, "%s0x%016llx", v == 0 ? "" : ", ", (unsigned long long)double__bits(decls[i].data_fvals[v]));
                    }
                } else {
                    for (int v = 0; v < decls[i].array_len; v++)
                        x86_emit_int_val(out, decls[i].data_vals[v], decls[i].data_val_is_label, decls[i].data_val_labels, v, v == 0);
                }
                fprintf(out, "\n");
            } else if (decls[i].is_ascii) {
                fprintf(out, "    %s: db ", decls[i].name);
                emit_x86_string_bytes(out, decls[i].str_val, decls[i].str_len);
                fprintf(out, "\n    %s_len: dq %d\n", decls[i].name, decls[i].str_len);
            } else if (decls[i].is_float) {
                if (decls[i].size_bytes == 4)
                    fprintf(out, "    %s: dd 0x%08x\n", decls[i].name, float__bits(decls[i].init_fvalue));
                else
                    fprintf(out, "    %s: dq 0x%016llx\n", decls[i].name, (unsigned long long)double__bits(decls[i].init_fvalue));
            } else {
                const char *dsz = decls[i].size_bytes == 1 ? "db" :
                                   decls[i].size_bytes == 2 ? "dw" :
                                   decls[i].size_bytes == 4 ? "dd" : "dq";
                fprintf(out, "    %s: %s %ld\n", decls[i].name, dsz, decls[i].init_value);
            }
        }
    }
    fprintf(out, "\nsection .bss\n");
    for (int i = 0; i < ndecls; i++) {
        if (decls[i].section == SEC_BSS) {
            if (decls[i].is_ascii) {
                /* 'bss ascii name[N];' -- N uninitialized bytes plus an
                   uninitialized 'name_len' qword, mirroring the
                   'name'/'name_len' pair a 'volatile ascii' decl emits
                   into .data, except both live in .bss here since
                   neither the bytes nor the length are known at
                   compile time (see the parser comment on this branch
                   for why name_len starts at 0, not N). */
                fprintf(out, "    %s: resb %d\n", decls[i].name, decls[i].array_len);
                fprintf(out, "    %s_len: resq 1\n", decls[i].name);
                continue;
            }
            const char *rsz = decls[i].size_bytes == 1 ? "resb" :
                               decls[i].size_bytes == 2 ? "resw" :
                               decls[i].size_bytes == 4 ? "resd" : "resq";
            /* resb/resw/resd/resq already take an element COUNT (not a
               byte count), so 'bss iK name[N];' is just N there instead
               of the scalar case's implicit 1 -- no different from how
               NASM's own '.bss'/resN pair works for a plain C-style
               array, and array_len is 0 for an ordinary scalar bss decl
               (see decl_t's own comment), so this one line covers both
               without a separate branch. */
            int count = decls[i].array_len > 0 ? decls[i].array_len : 1;
            fprintf(out, "    %s: %s %d\n", decls[i].name, rsz, count);
        }
    }
    if (g_uses_heap) {
        /* Static arena for alloc(): __heap_ptr starts pointing at the
           first byte of __heap and is bumped forward by each alloc(). */
        fprintf(out, "    %s: resb %ld\n", HEAP_SYM, g_heap_size_bytes);
        fprintf(out, "    %s: resq 1\n", HEAP_PTR_SYM);
    }

    fprintf(out, "\nsection .text\n");
    if (g_mode == MODE_BARE) {
        /* BARE/raw output: no 'global'/'extern' -- those are ELF
           symbol-table/linkage directives, meaningless (and, for
           'extern', actively wrong) when this file is assembled and
           dropped straight into a raw binary/image rather than linked
           as an ELF object. The entry label itself is still emitted
           as an ordinary ':' label below (see the OP_LABEL case), so
           whatever external tool (linker script, bootloader, custom
           crt0) is stitching this together can still find it by name. */
    } else {
        fprintf(out, "    global %s\n", entry_label);
        for (int i = 0; i < nexterns; i++) {
            if (externs[i].lib[0])
                fprintf(out, "    extern %s ; from -l%s -- see build note printed after compilation\n", externs[i].name, externs[i].lib);
            else
                fprintf(out, "    extern %s\n", externs[i].name);
        }
        if (g_libc_linked) fprintf(out, "    extern exit\n"); /* exit(N) calls libc's exit() when
                                                                   libc-linked -- see OP_EXIT above --
                                                                   so it needs its own extern even if
                                                                   the user never wrote 'extern exit(1);' */
    }
    fprintf(out, "\n");

    for (int i = 0; i < nprog; i++) {
        instr_t *ins = &prog[i];
        char sb[64], db[64];

        switch (ins->op) {
        case OP_LABEL:
            if (ins->is_entry && g_mode == MODE_BARE) {
                /* BARE mode: place the entry point at the chosen
                   'foot ADDR;' address instead of leaving placement to
                   an ELF linker -- see g_foot_addr's comment and
                   check_bare_mode_requirements. Emitted immediately
                   ahead of the label itself so this label (and every
                   instruction after it) assembles at exactly that
                   address when the output is assembled flat
                   (NASM '-f bin'). NASM's directive for this is called
                   'org' regardless of what Chard's own source-level
                   keyword is spelled ('foot') -- this line is emitting
                   NASM syntax, not echoing the Chard keyword. */
                fprintf(out, "org 0x%lx\n", g_foot_addr);
            }
            fprintf(out, "%s:\n", ins->dst.sym);
            if (ins->is_entry && g_argv_seen) {
                /* '%argv rN, rM;' capture -- must run before anything
                   else touches rsp (freestanding case reads argc/argv
                   directly off the incoming stack) or clobbers rdi/rsi
                   (libc case reads them out of the SysV ABI argument
                   registers main() was entered with), so this comes
                   first, ahead of even the heap seed below. See
                   do_argv_directive for the full rationale. */
                const char *argc_r = target_defs[TARGET_X86_64].regs[g_argv_argc_reg];
                const char *argv_r = target_defs[TARGET_X86_64].regs[g_argv_argv_reg];
                if (g_libc_linked) {
                    /* main(int argc, char **argv): argc in edi (32-bit;
                       moving the 32-bit sub-register name zero-extends
                       into the full 64-bit destination per the x86-64
                       ABI, so no separate widening step is needed),
                       argv in rsi. */
                    const char *argc_r32 = target_defs[TARGET_X86_64].regs_32[g_argv_argc_reg];
                    fprintf(out, "    mov %s, edi\n", argc_r32);
                    fprintf(out, "    mov %s, rsi\n", argv_r);
                } else {
                    /* Freestanding _start: the kernel hands off with
                       [rsp] = argc, [rsp+8] = argv[0] (i.e. rsp+8 is
                       argv itself) -- nothing in registers yet. Must be
                       read before OP_FRAME_OPEN's 'push rbp' changes
                       rsp out from under these offsets. */
                    fprintf(out, "    mov %s, [rsp]\n", argc_r);
                    fprintf(out, "    lea %s, [rsp+8]\n", argv_r);
                }
            }
            if (ins->is_entry && g_uses_heap) {
                /* Seed __heap_ptr = &__heap once, right as execution
                   begins, so it happens exactly once and before any
                   user code (including any alloc() call) can run. */
                fprintf(out, "    lea rax, [%s]\n", HEAP_SYM);
                fprintf(out, "    mov [%s], rax\n", HEAP_PTR_SYM);
            }
            break;

        case OP_FRAME_OPEN:
            /* Establishes this block's frame: save the caller's rbp,
               point rbp at the current rsp, then reserve frame_bytes
               for this block's locals (if any). The save/establish
               step always runs, even for a block with zero locals of
               its own -- a block can still nest another block that
               does have locals, and unconditionally giving every
               @label block its own rbp snapshot is what makes that
               nesting (and any push/pop inside a block that also has
               locals) safe: an inner block's rsp adjustments can never
               change what an outer block's "[rbp-N]" resolves to.
               x86-64 has no call-boundary alignment requirement of its
               own to round the reservation up to (unlike AArch64/
               RISC-V below), so the byte count from declare__local() is
               used as-is. */
            fprintf(out, "    push rbp\n");
            fprintf(out, "    mov rbp, rsp\n");
            if (ins->frame_bytes > 0) fprintf(out, "    sub rsp, %d\n", ins->frame_bytes);
            break;

        case OP_FRAME_CLOSE:
            /* 'mov rsp, rbp' undoes the reservation in one step
               (whatever it was, even if some other instruction moved
               rsp further within the block -- everything above rbp's
               saved slot is simply discarded), then 'pop rbp' restores
               the caller's frame pointer from where OP_FRAME_OPEN
               saved it. */
            fprintf(out, "    mov rsp, rbp\n");
            fprintf(out, "    pop rbp\n");
            break;

        case OP_MOV:
            if (ins->src.kind == OPND_IMM) {
                render_simple_operand(TARGET_X86_64, &ins->src, sb, sizeof(sb));
                fprintf(out, "    mov %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), sb);
            } else if (is_mem_operand(ins->src.kind)) {
                /* mov SYM > rX; / mov local > rX; -- bug fix: this branch
                   used to be missing, so a symbol/local source fell into
                   the plain-register else-branch below and called
                   reg__name() on an operand that was never a register,
                   reading garbage out of the wrong union member (visible
                   as 'mov rcx, (null)' in emitted output). Same
                   scratch-load-then-mov shape every other two-operand op
                   already uses for a memory source (see OP_ADD/OP_SUB/
                   etc above, or OP_NOT/OP_NEG below). */
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    mov %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), SCRATCH_X86);
            } else {
                fprintf(out, "    mov %s, %s\n", reg__name(TARGET_X86_64, &ins->dst),
                        reg__name(TARGET_X86_64, &ins->src));
            }
            break;

        case OP_LOAD: {
            int sz = operand_mem_size(&ins->src);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst); /* 64-bit name; movzx/movsx/plain mov all widen into it */
            char addr[64];
            x86_addr_text(out, &ins->src, addr, sizeof(addr));
            if (ins->load_signed) {
                if (sz == 1) fprintf(out, "    movsx %s, byte [%s]\n", dstreg, addr);
                else if (sz == 2) fprintf(out, "    movsx %s, word [%s]\n", dstreg, addr);
                else if (sz == 4) fprintf(out, "    movsxd %s, dword [%s]\n", dstreg, addr);
                else fprintf(out, "    mov %s, [%s]\n", dstreg, addr);
            } else {
                if (sz == 1) fprintf(out, "    movzx %s, byte [%s]\n", dstreg, addr);
                else if (sz == 2) fprintf(out, "    movzx %s, word [%s]\n", dstreg, addr);
                else if (sz == 4) fprintf(out, "    mov %s, dword [%s]\n", width_reg_name(TARGET_X86_64, &ins->dst, 4), addr); /* zero-extends to 64-bit */
                else fprintf(out, "    mov %s, [%s]\n", dstreg, addr);
            }
            break;
        }

        case OP_STORE: {
            int sz = operand_mem_size(&ins->dst);
            const char *srcreg = width_reg_name(TARGET_X86_64, &ins->src, sz);
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : NULL;
            char addr[64];
            x86_addr_text(out, &ins->dst, addr, sizeof(addr));
            if (sizeword) fprintf(out, "    mov %s [%s], %s\n", sizeword, addr, srcreg);
            else fprintf(out, "    mov [%s], %s\n", addr, srcreg);
            break;
        }

        case OP_LEA: {
            /* Address of the symbol itself (not its value) -- NASM
               resolves [SYM] to a RIP-relative lea automatically, and
               the same instruction works unchanged for an sp-relative
               local address. */
            char addr[64];
            x86_addr_text(out, &ins->src, addr, sizeof(addr));
            fprintf(out, "    lea %s, [%s]\n", reg__name(TARGET_X86_64, &ins->dst), addr);
            break;
        }

        case OP_ADD: case OP_SUB: case OP_AND: case OP_OR: case OP_XOR: case OP_CMP: {
            const char *mn = ins->op == OP_ADD ? "add" : ins->op == OP_SUB ? "sub" :
                              ins->op == OP_AND ? "and" : ins->op == OP_OR ? "or" :
                              ins->op == OP_XOR ? "xor" : "cmp";
            if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), SCRATCH_X86);
            } else {
                render_simple_operand(TARGET_X86_64, &ins->src, sb, sizeof(sb));
                fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), sb);
            }
            break;
        }

        /* x86-64's shl/shr only accept an *immediate* count or the
           fixed register 'cl' (the low byte of rcx) -- unlike
           AArch64's lsl/lsr and RISC-V's sll/srl, which take the
           count in any general register. 'shl rax, rbx' is not a
           real encoding, so a variable (register) shift count has to
           be staged through cl specifically, not emitted directly the
           way add/sub/and/or/xor/cmp are above.
           rcx (Chard's r3) is an ordinary, user-allocatable register
           here, not scratch, so it may already hold a live value the
           rest of the function still needs -- it has to be saved and
           restored around the shift unless it's already the register
           supplying the count (in which case it's already exactly
           where it needs to be and nothing needs saving), or the
           immediate-count path handles it directly without touching
           rcx/cl at all. */
        case OP_SHL: case OP_SHR: {
            const char *mn = ins->op == OP_SHL ? "shl" : "shr";
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    %s %s, %ld\n", mn, dstreg, ins->src.imm);
                break;
            }
            /* Register (or memory-backed, which loads into a register
               first) count: stage it into cl. */
            int count_is_rcx = (ins->src.kind == OPND_REG && !ins->src.is_sp &&
                                 !ins->src.is_float && ins->src.reg_num == 3 /* r3 == rcx */);
            int dst_is_rcx = (!ins->dst.is_sp && !ins->dst.is_float && ins->dst.reg_num == 3);
            if (count_is_rcx) {
                /* Count is already in rcx/cl -- nothing to save, just shift. */
                fprintf(out, "    %s %s, cl\n", mn, dstreg);
            } else if (dst_is_rcx) {
                /* dst *is* rcx, and src is some other register/mem
                   holding the count. Stage the count through the
                   scratch register first (so writing cl below doesn't
                   destroy it before it's read), then shift rcx by
                   itself's low byte after moving the count in -- but
                   since dst is rcx, the shift target and the cl source
                   overlap, so move count -> scratch -> cl, remembering
                   dst's original value isn't in danger (dst == rcx is
                   the thing being shifted, not the count). */
                if (is_mem_operand(ins->src.kind)) {
                    emit_x86_load_scratch(out, &ins->src);
                    fprintf(out, "    mov cl, %sb\n", SCRATCH_X86);
                } else {
                    fprintf(out, "    mov cl, %s\n", width_reg_name(TARGET_X86_64, &ins->src, 1));
                }
                fprintf(out, "    %s %s, cl\n", mn, dstreg);
            } else {
                /* General case: rcx is live with an unrelated value.
                   Save it, load the count into cl, shift, restore. */
                fprintf(out, "    push rcx\n");
                if (is_mem_operand(ins->src.kind)) {
                    emit_x86_load_scratch(out, &ins->src);
                    fprintf(out, "    mov cl, %sb\n", SCRATCH_X86);
                } else {
                    fprintf(out, "    mov cl, %s\n", width_reg_name(TARGET_X86_64, &ins->src, 1));
                }
                fprintf(out, "    %s %s, cl\n", mn, dstreg);
                fprintf(out, "    pop rcx\n");
            }
            break;
        }

        case OP_NOT: case OP_NEG: {
            /* x86-64 'not'/'neg' are true unary instructions (single
               operand, in place) -- so unlike the OP_ADD/OP_SUB/etc
               block above, src is never combined with a separate dst
               operand. Move src into dst first (no-op when they're
               already the same register, e.g. 'not r1 > r1'), then
               apply the unary op to dst. */
            const char *mn = ins->op == OP_NOT ? "not" : "neg";
            if (ins->src.kind == OPND_REG && ins->src.reg_num == ins->dst.reg_num) {
                /* already in dst; skip the redundant self-mov */
            } else if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    mov %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), SCRATCH_X86);
            } else {
                render_simple_operand(TARGET_X86_64, &ins->src, sb, sizeof(sb));
                fprintf(out, "    mov %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), sb);
            }
            fprintf(out, "    %s %s\n", mn, reg__name(TARGET_X86_64, &ins->dst));
            break;
        }

        case OP_ROTL: case OP_ROTR: {
            /* Same cl-staging dance as OP_SHL/OP_SHR above (rol/ror
               share the exact same "count must be in cl unless it's an
               immediate" hardware constraint as shl/shr) -- copied
               rather than merged into one case because the shl/shr
               block above is already interleaved with its own dst==rcx
               special-casing, and duplicating the ~15 lines here reads
               more clearly than threading a mnemonic parameter through
               that existing block. */
            const char *mn = ins->op == OP_ROTL ? "rol" : "ror";
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    %s %s, %ld\n", mn, dstreg, ins->src.imm);
                break;
            }
            int count_is_rcx = (ins->src.kind == OPND_REG && !ins->src.is_sp &&
                                 !ins->src.is_float && ins->src.reg_num == 3);
            int dst_is_rcx = (!ins->dst.is_sp && !ins->dst.is_float && ins->dst.reg_num == 3);
            if (count_is_rcx) {
                fprintf(out, "    %s %s, cl\n", mn, dstreg);
            } else if (dst_is_rcx) {
                if (is_mem_operand(ins->src.kind)) {
                    emit_x86_load_scratch(out, &ins->src);
                    fprintf(out, "    mov cl, %sb\n", SCRATCH_X86);
                } else {
                    fprintf(out, "    mov cl, %s\n", width_reg_name(TARGET_X86_64, &ins->src, 1));
                }
                fprintf(out, "    %s %s, cl\n", mn, dstreg);
            } else {
                fprintf(out, "    push rcx\n");
                if (is_mem_operand(ins->src.kind)) {
                    emit_x86_load_scratch(out, &ins->src);
                    fprintf(out, "    mov cl, %sb\n", SCRATCH_X86);
                } else {
                    fprintf(out, "    mov cl, %s\n", width_reg_name(TARGET_X86_64, &ins->src, 1));
                }
                fprintf(out, "    %s %s, cl\n", mn, dstreg);
                fprintf(out, "    pop rcx\n");
            }
            break;
        }

        case OP_POPCOUNT: {
            /* popcnt is a true reg,reg/mem instruction -- no rax:rdx or
               cl-style fixed-operand constraints like idiv/shl, so this
               is a direct single-instruction emission once src is in a
               register. Baseline assumption (popcnt requires the ABM/
               SSE4.2 popcnt feature bit) matches this project's existing
               "one flat baseline, not a family of -march variants"
               stance used elsewhere for lzcnt/tzcnt below. */
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    popcnt %s, %s\n", dstreg, SCRATCH_X86);
            } else if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s, %ld\n", SCRATCH_X86, ins->src.imm);
                fprintf(out, "    popcnt %s, %s\n", dstreg, SCRATCH_X86);
            } else {
                fprintf(out, "    popcnt %s, %s\n", dstreg, reg__name(TARGET_X86_64, &ins->src));
            }
            break;
        }

        case OP_CLZ: case OP_CTZ: {
            /* lzcnt/tzcnt (not bsr/bsf, which are undefined at zero and
               -- for bsr -- give a bit *index* rather than a leading-
               zero *count*, requiring an extra 63-x correction). Same
               operand shape as popcnt above. */
            const char *mn = ins->op == OP_CLZ ? "lzcnt" : "tzcnt";
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    %s %s, %s\n", mn, dstreg, SCRATCH_X86);
            } else if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s, %ld\n", SCRATCH_X86, ins->src.imm);
                fprintf(out, "    %s %s, %s\n", mn, dstreg, SCRATCH_X86);
            } else {
                fprintf(out, "    %s %s, %s\n", mn, dstreg, reg__name(TARGET_X86_64, &ins->src));
            }
            break;
        }

        case OP_SEXT: case OP_ZEXT: {
            /* movsx/movzx take a full-width destination and a narrower
               source register (or memory operand, unused here since
               sext/zext's source is restricted to reg/imm at parse
               time -- see the parser comment). An immediate source has
               to be materialized into SCRATCH_X86 first, narrowed to
               the right sub-register width via the r14d/r14w/r14b
               suffix trick already used elsewhere (e.g. the shl/shr
               'mov cl, %sb' sites above), then movsx/movzx reads FROM
               that narrowed view -- movsx/movzx never accept a bare
               immediate operand directly. 32-bit sign-extension is the
               one width movsx itself can't do (it only extends 8/16-bit
               sources); x86-64 defines a separate movsxd for exactly
               that case. 32-bit zero-extension needs no dedicated
               instruction at all: an ordinary 32-bit 'mov' into eax/
               ecx/etc already zero-extends into the full 64-bit
               register as an architectural guarantee, so zext32 is
               just a mov into the narrowed destination view. */
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int is_sext = ins->op == OP_SEXT;
            const char *srcnarrow;
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s, %ld\n", SCRATCH_X86, ins->src.imm);
                srcnarrow = ins->elem_size == 1 ? "r14b" : ins->elem_size == 2 ? "r14w" : "r14d";
            } else {
                srcnarrow = width_reg_name(TARGET_X86_64, &ins->src, ins->elem_size);
            }
            if (ins->elem_size == 4) {
                if (is_sext) {
                    fprintf(out, "    movsxd %s, %s\n", dstreg, srcnarrow);
                } else {
                    /* mov into the 32-bit view of dst zero-extends the
                       upper 32 bits for free -- see comment above. */
                    const char *dst32 = width_reg_name(TARGET_X86_64, &ins->dst, 4);
                    fprintf(out, "    mov %s, %s\n", dst32, srcnarrow);
                }
            } else {
                fprintf(out, "    %s %s, %s\n", is_sext ? "movsx" : "movzx", dstreg, srcnarrow);
            }
            break;
        }

        case OP_SAT_ADD: case OP_SAT_SUB: {
            /* Ordinary add/sub first (sets OF on signed overflow), then
               a branch-free clamp: cmovo replaces dst with INT64_MAX or
               INT64_MIN only when OF was actually set, leaving the
               ordinary result untouched otherwise. Getting the *correct*
               saturation direction (MAX vs MIN) from a single OF check
               needs the sign of the result: on overflow, dst's top bit
               already tells us which way it overflowed (add: overflowed
               positive-positive wraps to a negative-looking result, so
               a negative-after-overflow dst means saturate to MAX, and
               vice versa for sub) -- so the clamp value itself is
               selected with a second cmovs, keyed off dst's own sign,
               executed only along the already-overflowed path's data
               dependency (both cmovs read the same OF/SF that the
               add/sub itself just set, no extra cmp needed). */
            const char *mn = ins->op == OP_SAT_ADD ? "add" : "sub";
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    %s %s, %s\n", mn, dstreg, SCRATCH_X86);
            } else {
                render_simple_operand(TARGET_X86_64, &ins->src, sb, sizeof(sb));
                fprintf(out, "    %s %s, %s\n", mn, dstreg, sb);
            }
            fprintf(out, "    push rax\n");
            fprintf(out, "    mov %s, 0x8000000000000000\n", SCRATCH_X86);
            fprintf(out, "    mov rax, 0x7fffffffffffffff\n");
            fprintf(out, "    cmovs %s, rax\n", SCRATCH_X86);
            fprintf(out, "    pop rax\n");
            fprintf(out, "    cmovo %s, %s\n", dstreg, SCRATCH_X86);
            break;
        }

        case OP_MUL:
            /* x86-64 imul supports reg, reg/imm directly */
            if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    imul %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), SCRATCH_X86);
            } else {
                render_simple_operand(TARGET_X86_64, &ins->src, sb, sizeof(sb));
                fprintf(out, "    imul %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), sb);
            }
            break;

        case OP_DIV: case OP_MOD:
            /* x86-64 idiv is fixed-operand: rdx:rax / src -> quotient in
               rax, remainder in rdx, both from one instruction. div keeps
               rax, mod keeps rdx -- nothing here is discarded silently.
               r1/r4 map directly onto rax/rdx (see the r1-r12 mapping),
               so 'mov rax, dst' followed by 'cqo' can clobber a src or
               dst that happens to live in rax or rdx *before* idiv ever
               reads it: 'mov rax, dst' overwrites rax first (destroying
               a divisor that was sitting there if src==r1), and 'cqo'
               overwrites rdx next (destroying a divisor that was
               sitting there if src==r4) -- either way idiv would end up
               dividing by the wrong value, silently, with no error.
               The fix: always resolve src into SCRATCH_X86 (r14, always
               disjoint from the r1-r12 mapping) *before* touching
               rax/rdx at all, so idiv's divisor operand is never
               rax/rdx itself and can never be clobbered by the
               mov-rax/cqo sequence that has to run first. */
            if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
            } else if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s, %ld\n", SCRATCH_X86, ins->src.imm);
            } else {
                fprintf(out, "    mov %s, %s\n", SCRATCH_X86, reg__name(TARGET_X86_64, &ins->src));
            }
            fprintf(out, "    mov rax, %s\n", reg__name(TARGET_X86_64, &ins->dst));
            fprintf(out, "    cqo\n");
            fprintf(out, "    idiv %s\n", SCRATCH_X86);
            fprintf(out, "    mov %s, %s\n", reg__name(TARGET_X86_64, &ins->dst),
                    ins->op == OP_DIV ? "rax" : "rdx");
            break;

        case OP_JMP: fprintf(out, "    jmp %s\n", ins->dst.kind == OPND_REG ? reg__name(TARGET_X86_64, &ins->dst) : ins->dst.sym); break;
        case OP_JE:  fprintf(out, "    je %s\n", ins->dst.sym); break;
        case OP_JNE: fprintf(out, "    jne %s\n", ins->dst.sym); break;
        case OP_JG:  fprintf(out, "    jg %s\n", ins->dst.sym); break;
        case OP_JL:  fprintf(out, "    jl %s\n", ins->dst.sym); break;
        case OP_JGE: fprintf(out, "    jge %s\n", ins->dst.sym); break;
        case OP_JLE: fprintf(out, "    jle %s\n", ins->dst.sym); break;
        case OP_JA:  fprintf(out, "    ja %s\n", ins->dst.sym); break;
        case OP_JB:  fprintf(out, "    jb %s\n", ins->dst.sym); break;
        case OP_JAE: fprintf(out, "    jae %s\n", ins->dst.sym); break;
        case OP_JBE: fprintf(out, "    jbe %s\n", ins->dst.sym); break;

        case OP_ASSERT: {
            /* assert LHS OP RHS; -- the preceding OP_CMP (emitted by
               parse_cond_and_emit_cmp_ex) already set flags.
               assert_jmp_op is the *inverted* condition (from
               invert_cond_op, the same inversion if/while use to skip
               their body when the written condition is false) -- so
               taking that jump means "the asserted condition was
               false", and that's exactly when this should trap: jump
               straight to a trap label on assert_jmp_op, otherwise fall
               straight through past it (the ok_label immediately
               after). 'ud2' is x86's dedicated illegal-instruction
               trap. */
            int id = g_label_counter++;
            char trap_label[MAX_SYMLEN], ok_label[MAX_SYMLEN];
            snprintf(trap_label, sizeof(trap_label), ".Lassert%d_trap", id);
            snprintf(ok_label, sizeof(ok_label), ".Lassert%d_ok", id);
            static const char *jmp_mnemonic[] = {
                [OP_JE]="je", [OP_JNE]="jne", [OP_JG]="jg", [OP_JL]="jl",
                [OP_JGE]="jge", [OP_JLE]="jle", [OP_JA]="ja", [OP_JB]="jb",
                [OP_JAE]="jae", [OP_JBE]="jbe"
            };
            fprintf(out, "    %s %s\n", jmp_mnemonic[ins->assert_jmp_op], trap_label);
            fprintf(out, "    jmp %s\n", ok_label);
            fprintf(out, "%s:\n", trap_label);
            fprintf(out, "    ud2\n");
            fprintf(out, "%s:\n", ok_label);
            break;
        }

        case OP_CALL: fprintf(out, "    call %s\n", ins->dst.kind == OPND_REG ? reg__name(TARGET_X86_64, &ins->dst) : ins->dst.sym); break;
        case OP_RET:  fprintf(out, "    ret\n"); break;

        case OP_EXIT:
            /* src is either OPND_IMM (exit(N)) or OPND_REG (exit(rN)) --
               see parse-time check above; emit a mov from whichever it
               actually is instead of assuming .imm like before. */
            if (g_libc_linked) {
                /* libc-init'd programs must exit through libc's own
                   exit(), not the raw exit_group syscall -- exit_group
                   tears down the process immediately, before libc gets
                   a chance to flush stdio's buffers (printf's output,
                   notably) or run any atexit-registered cleanup. Same
                   C ABI call OP_LIBC_CALL uses (arg in rdi), just
                   inlined here since 'exit(N)' is its own statement,
                   not spelled as a libcall. */
                if (ins->src.kind == OPND_REG)
                    fprintf(out, "    mov rdi, %s\n", reg__name(TARGET_X86_64, &ins->src));
                else
                    fprintf(out, "    mov rdi, %ld\n", ins->src.imm);
                fprintf(out, "    call exit\n");
            } else {
                fprintf(out, "    mov rax, 60\n");
                if (ins->src.kind == OPND_REG)
                    fprintf(out, "    mov rdi, %s\n", reg__name(TARGET_X86_64, &ins->src));
                else
                    fprintf(out, "    mov rdi, %ld\n", ins->src.imm);
                fprintf(out, "    syscall\n");
            }
            break;

        case OP_HALT:
            /* 'hlt' stops the CPU until the next interrupt; wrapped in
               its own label+jmp loop so a spurious wake (any maskable
               interrupt firing while flags still permit it) falls
               back into another 'hlt' instead of into whatever bytes
               happen to sit right after this instruction in memory --
               see OP_HALT's declaration. */
            {
                int id = g_label_counter++;
                fprintf(out, ".Lhalt%d:\n", id);
                fprintf(out, "    hlt\n");
                fprintf(out, "    jmp .Lhalt%d\n", id);
            }
            break;

        case OP_STDOUT:
            /* write(1, msg, msg_len). For a global ascii symbol, length
               comes from the compiler-generated <name>_len symbol,
               visible in this same file. For a 'local ascii' buffer
               (src.kind == OPND_LOCAL), there is no such linker symbol
               -- msg_len is instead a second real local (dst, set up by
               out()'s parsing), addressed the same fp-relative way any
               other local operand is (see x86_addr_text). */
            fprintf(out, "    mov rax, 1\n");
            fprintf(out, "    mov rdi, 1\n");
            if (ins->src.kind == OPND_LOCAL) {
                char addr[64], lenaddr[64];
                x86_addr_text(out, &ins->src, addr, sizeof(addr));
                x86_addr_text(out, &ins->dst, lenaddr, sizeof(lenaddr));
                fprintf(out, "    lea rsi, [%s]\n", addr);
                fprintf(out, "    mov rdx, [%s]\n", lenaddr);
            } else {
                fprintf(out, "    lea rsi, [%s]\n", ins->src.sym);
                fprintf(out, "    mov rdx, [%s_len]\n", ins->src.sym);
            }
            fprintf(out, "    syscall\n");
            break;

        case OP_ALLOC: {
            /* Bump allocator: dst = __heap_ptr (the block base); then
               __heap_ptr += size. Size may be an immediate, a register,
               or a symbol (whose value is loaded through the scratch
               register, same as every other operand-reading op here).

               The register-source case reads src into SCRATCH_X86
               BEFORE dst is overwritten with the base pointer below --
               unlike the mem-operand and immediate cases, a register
               source can alias dst (Chard has no parser check requiring
               'alloc(rN) > rM' to use distinct registers, unlike e.g.
               i2s/s2i/bcmp, and there's no reason a caller wouldn't
               reuse the same register for a computed size and the
               result, since alloc's whole point is to overwrite dst
               anyway). Reading srcreg into scratch first, then
               clobbering dst with the base pointer, then adding from
               scratch (never from dst or srcreg again) means the size
               is captured correctly regardless of that aliasing --
               matching how the AArch64/RISC-V OP_ALLOC cases already
               handle this (they compute the new pointer into a
               dedicated scratch register distinct from dst, so dst's
               post-load value is never re-read as an input). Emitting
               'mov scratch, srcreg' unconditionally (even though it's
               a redundant self-mov in the never-aliased case) keeps
               this one code path correct for both, rather than trying
               to special-case only the aliased register source. */
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                fprintf(out, "    mov %s, [%s]\n", dstreg, HEAP_PTR_SYM);
                fprintf(out, "    add [%s], %s\n", HEAP_PTR_SYM, SCRATCH_X86);
            } else if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s, [%s]\n", dstreg, HEAP_PTR_SYM);
                fprintf(out, "    add qword [%s], %ld\n", HEAP_PTR_SYM, ins->src.imm);
            } else {
                fprintf(out, "    mov %s, %s\n", SCRATCH_X86, reg__name(TARGET_X86_64, &ins->src));
                fprintf(out, "    mov %s, [%s]\n", dstreg, HEAP_PTR_SYM);
                fprintf(out, "    add [%s], %s\n", HEAP_PTR_SYM, SCRATCH_X86);
            }
            break;
        }

        case OP_HEAP_RESET:
            /* Reclaim the whole arena: __heap_ptr = &__heap. Uses
               SCRATCH_X86 (r14), not rax, since -- unlike the one-time
               entry-point seeding this mirrors -- hp-reset; can occur
               mid-program with a live value in rax that must survive. */
            fprintf(out, "    lea %s, [%s]\n", SCRATCH_X86, HEAP_SYM);
            fprintf(out, "    mov [%s], %s\n", HEAP_PTR_SYM, SCRATCH_X86);
            break;

        case OP_ILOAD: {
            /* rDST = *(base + idx*elem_size), with load width behaving
               the same as OP_LOAD: zero- or sign-extends into the full
               64-bit destination register depending on load_signed.
               NASM's [base + idx*scale] addressing handles the scale
               directly -- no separate multiply needed. */
            const char *basereg = reg__name(TARGET_X86_64, &ins->base_reg);
            const char *idxreg = reg__name(TARGET_X86_64, &ins->idx_reg);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int sz = ins->elem_size;
            if (ins->load_signed) {
                if (sz == 1) fprintf(out, "    movsx %s, byte [%s + %s*1]\n", dstreg, basereg, idxreg);
                else if (sz == 2) fprintf(out, "    movsx %s, word [%s + %s*2]\n", dstreg, basereg, idxreg);
                else if (sz == 4) fprintf(out, "    movsxd %s, dword [%s + %s*4]\n", dstreg, basereg, idxreg);
                else fprintf(out, "    mov %s, [%s + %s*8]\n", dstreg, basereg, idxreg);
            } else {
                if (sz == 1) fprintf(out, "    movzx %s, byte [%s + %s*1]\n", dstreg, basereg, idxreg);
                else if (sz == 2) fprintf(out, "    movzx %s, word [%s + %s*2]\n", dstreg, basereg, idxreg);
                else if (sz == 4) fprintf(out, "    mov %s, dword [%s + %s*4]\n", width_reg_name(TARGET_X86_64, &ins->dst, 4), basereg, idxreg);
                else fprintf(out, "    mov %s, [%s + %s*8]\n", dstreg, basereg, idxreg);
            }
            break;
        }

        case OP_ISTORE: {
            const char *basereg = reg__name(TARGET_X86_64, &ins->base_reg);
            const char *idxreg = reg__name(TARGET_X86_64, &ins->idx_reg);
            int sz = ins->elem_size;
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : "qword";
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s [%s + %s*%d], %ld\n", sizeword, basereg, idxreg, sz, ins->src.imm);
            } else if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                const char *srcreg = sz == 1 ? "r14b" : sz == 2 ? "r14w" : sz == 4 ? "r14d" : SCRATCH_X86;
                fprintf(out, "    mov %s [%s + %s*%d], %s\n", sizeword, basereg, idxreg, sz, srcreg);
            } else {
                const char *srcreg = width_reg_name(TARGET_X86_64, &ins->src, sz);
                fprintf(out, "    mov %s [%s + %s*%d], %s\n", sizeword, basereg, idxreg, sz, srcreg);
            }
            break;
        }

        case OP_HFIELD_LOAD: {
            /* rDST = *(rBASE + const_offset), no scaling -- a struct
               field's byte offset is already an absolute constant (see
               struct_field_t.offset), not idx*elem_size the way
               OP_ILOAD's runtime index is. NASM folds a plain constant
               into the same [base + disp] addressing form it already
               uses for OP_LALOAD's compile-time-known base. */
            const char *basereg = reg__name(TARGET_X86_64, &ins->base_reg);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int sz = ins->elem_size;
            int off = ins->const_offset;
            char addr[64];
            snprintf(addr, sizeof(addr), "%s+%d", basereg, off);
            if (sz == 1) fprintf(out, "    movzx %s, byte [%s]\n", dstreg, addr);
            else if (sz == 2) fprintf(out, "    movzx %s, word [%s]\n", dstreg, addr);
            else if (sz == 4) fprintf(out, "    mov %s, dword [%s]\n", width_reg_name(TARGET_X86_64, &ins->dst, 4), addr);
            else fprintf(out, "    mov %s, [%s]\n", dstreg, addr);
            break;
        }

        case OP_HFIELD_STORE: {
            const char *basereg = reg__name(TARGET_X86_64, &ins->base_reg);
            int sz = ins->elem_size;
            int off = ins->const_offset;
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : "qword";
            char addr[64];
            snprintf(addr, sizeof(addr), "%s+%d", basereg, off);
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s [%s], %ld\n", sizeword, addr, ins->src.imm);
            } else if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                const char *srcreg = sz == 1 ? "r14b" : sz == 2 ? "r14w" : sz == 4 ? "r14d" : SCRATCH_X86;
                fprintf(out, "    mov %s [%s], %s\n", sizeword, addr, srcreg);
            } else {
                const char *srcreg = width_reg_name(TARGET_X86_64, &ins->src, sz);
                fprintf(out, "    mov %s [%s], %s\n", sizeword, addr, srcreg);
            }
            break;
        }

        case OP_XLOAD: {
            /* rDST = *(base + idx*scale + disp). NASM's own
               [base + idx*scale + disp] addressing form takes all
               three parts directly -- scale is restricted to 1/2/4/8
               at parse time (see parse__xaddr), exactly the set x86's
               SIB byte natively supports, so no separate multiply is
               ever needed here, same as OP_ILOAD's fixed-scale case. */
            const char *basereg = reg__name(TARGET_X86_64, &ins->base_reg);
            const char *idxreg = reg__name(TARGET_X86_64, &ins->idx_reg);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int sz = ins->elem_size;
            int scale = ins->xaddr_scale;
            int off = ins->const_offset;
            char addr[80];
            snprintf(addr, sizeof(addr), "%s + %s*%d%+d", basereg, idxreg, scale, off);
            if (sz == 1) fprintf(out, "    movzx %s, byte [%s]\n", dstreg, addr);
            else if (sz == 2) fprintf(out, "    movzx %s, word [%s]\n", dstreg, addr);
            else if (sz == 4) fprintf(out, "    mov %s, dword [%s]\n", width_reg_name(TARGET_X86_64, &ins->dst, 4), addr);
            else fprintf(out, "    mov %s, [%s]\n", dstreg, addr);
            break;
        }

        case OP_XSTORE: {
            const char *basereg = reg__name(TARGET_X86_64, &ins->base_reg);
            const char *idxreg = reg__name(TARGET_X86_64, &ins->idx_reg);
            int sz = ins->elem_size;
            int scale = ins->xaddr_scale;
            int off = ins->const_offset;
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : "qword";
            char addr[80];
            snprintf(addr, sizeof(addr), "%s + %s*%d%+d", basereg, idxreg, scale, off);
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s [%s], %ld\n", sizeword, addr, ins->src.imm);
            } else if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                const char *srcreg = sz == 1 ? "r14b" : sz == 2 ? "r14w" : sz == 4 ? "r14d" : SCRATCH_X86;
                fprintf(out, "    mov %s [%s], %s\n", sizeword, addr, srcreg);
            } else {
                const char *srcreg = width_reg_name(TARGET_X86_64, &ins->src, sz);
                fprintf(out, "    mov %s [%s], %s\n", sizeword, addr, srcreg);
            }
            break;
        }

        case OP_PTRADD: case OP_PTRSUB: {
            /* rDST = base +/- (idx*scale + disp), or rDST = base +/-
               disp when idx_reg is absent (the bracket-less
               'ptradd/ptrsub rBASE + DISP > rDST;' form -- see its
               parse-time comment). NASM's 'lea' computes
               [base + idx*scale + disp] directly for the add case,
               same addressing text OP_XLOAD already builds. There is
               no negative-scale SIB form to lean on for ptrsub, so
               that case is built explicitly: idx*scale is computed
               into dst first (via lea, so the scale multiply is free),
               negated, then base and -disp are added on top -- one
               small instruction sequence rather than a second
               addressing-text path. */
            const char *basereg = reg__name(TARGET_X86_64, &ins->base_reg);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int off = ins->const_offset;
            int is_sub = (ins->op == OP_PTRSUB);
            if (ins->idx_reg.kind == OPND_REG) {
                const char *idxreg = reg__name(TARGET_X86_64, &ins->idx_reg);
                int scale = ins->xaddr_scale;
                if (!is_sub) {
                    char addr[80];
                    snprintf(addr, sizeof(addr), "%s + %s*%d%+d", basereg, idxreg, scale, off);
                    fprintf(out, "    lea %s, [%s]\n", dstreg, addr);
                } else {
                    if (scale == 1) fprintf(out, "    mov %s, %s\n", dstreg, idxreg);
                    else fprintf(out, "    lea %s, [%s*%d]\n", dstreg, idxreg, scale);
                    fprintf(out, "    neg %s\n", dstreg);
                    fprintf(out, "    add %s, %s\n", dstreg, basereg);
                    if (off != 0) fprintf(out, "    sub %s, %d\n", dstreg, off);
                }
            } else {
                /* No index: plain base +/- disp. */
                int d = is_sub ? -off : off;
                if (d == 0) fprintf(out, "    mov %s, %s\n", dstreg, basereg);
                else fprintf(out, "    lea %s, [%s%+d]\n", dstreg, basereg, d);
            }
            break;
        }

        case OP_LALOAD: {
            /* rDST = local array element at idx, addressed as
               [rbp - base_offset + idx*elem_size] -- base_offset is
               element 0's fixed offset (see declare_local_array), so
               NASM's own addressing syntax handles the scale/offset
               arithmetic directly, the same way OP_ILOAD's
               [base + idx*scale] does, just with a compile-time base
               instead of a runtime register. A literal index (allowed
               at parse time, see laloadN's parsing) folds directly into
               the constant offset instead of emitting register-scaled
               addressing, since there's nothing to scale at runtime in
               that case. frames_up > 0 (the array lives in an enclosing
               block) chases the saved-fp chain first, same as any other
               local access -- see x86_addr_text's sibling reasoning. */
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int sz = ins->elem_size;
            const char *base = "rbp";
            if (ins->src.frames_up > 0) {
                fprintf(out, "    mov %s, [rbp]\n", SCRATCH_X86);
                for (int k = 1; k < ins->src.frames_up; k++)
                    fprintf(out, "    mov %s, [%s]\n", SCRATCH_X86, SCRATCH_X86);
                base = SCRATCH_X86;
            }
            char addr[80];
            if (ins->idx_reg.kind == OPND_IMM) {
                long total_off = ins->src.local_offset - ins->idx_reg.imm * sz;
                snprintf(addr, sizeof(addr), "%s%+ld", base, -total_off);
            } else {
                const char *idxreg = reg__name(TARGET_X86_64, &ins->idx_reg);
                snprintf(addr, sizeof(addr), "%s-%d+%s*%d", base, ins->src.local_offset, idxreg, sz);
            }
            if (sz == 1) fprintf(out, "    movzx %s, byte [%s]\n", dstreg, addr);
            else if (sz == 2) fprintf(out, "    movzx %s, word [%s]\n", dstreg, addr);
            else if (sz == 4) fprintf(out, "    mov %s, dword [%s]\n", width_reg_name(TARGET_X86_64, &ins->dst, 4), addr);
            else fprintf(out, "    mov %s, [%s]\n", dstreg, addr);
            break;
        }

        case OP_LASTORE: {
            int sz = ins->elem_size;
            const char *sizeword2 = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : "qword";
            const char *base = "rbp";
            if (ins->dst.frames_up > 0) {
                fprintf(out, "    mov %s, [rbp]\n", SCRATCH_X86);
                for (int k = 1; k < ins->dst.frames_up; k++)
                    fprintf(out, "    mov %s, [%s]\n", SCRATCH_X86, SCRATCH_X86);
                base = SCRATCH_X86;
            }
            char addr[80];
            if (ins->idx_reg.kind == OPND_IMM) {
                long total_off = ins->dst.local_offset - ins->idx_reg.imm * sz;
                snprintf(addr, sizeof(addr), "%s%+ld", base, -total_off);
            } else {
                const char *idxreg = reg__name(TARGET_X86_64, &ins->idx_reg);
                snprintf(addr, sizeof(addr), "%s-%d+%s*%d", base, ins->dst.local_offset, idxreg, sz);
            }
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s [%s], %ld\n", sizeword2, addr, ins->src.imm);
            } else if (is_mem_operand(ins->src.kind)) {
                emit_x86_load_scratch(out, &ins->src);
                const char *srcreg = sz == 1 ? "r14b" : sz == 2 ? "r14w" : sz == 4 ? "r14d" : SCRATCH_X86;
                fprintf(out, "    mov %s [%s], %s\n", sizeword2, addr, srcreg);
            } else {
                const char *srcreg = width_reg_name(TARGET_X86_64, &ins->src, sz);
                fprintf(out, "    mov %s [%s], %s\n", sizeword2, addr, srcreg);
            }
            break;
        }

        case OP_PUSH:
            /* Native x86-64 push always moves rsp by stack_slot_size()
               (see the table up top, currently 8) and works directly
               on a register or a sign-extended immediate -- but ONLY
               for a general-purpose register: 'push xmm0' is not a
               valid x86-64 instruction at all (push/pop are GPR-only;
               there's no SIMD/xmm form). A float source (f1-f7/s1-s7 --
               is_float, either width) has to go through 'sub rsp, N'
               plus a scalar move instead, mirroring how a real function
               prologue spills an xmm register: decrement rsp by
               stack_slot_size() first (keeping the same per-slot size
               as an integer push, so restore_seq's pop side -- which
               doesn't know or care whether the slot it's popping held
               an int or a float -- stays correctly aligned), then
               movsd/movss to [rsp]. movsd (not movss) for f64 even
               though only the low 8 bytes are meaningful for a true
               f32 -- writing the full 8-byte slot either way keeps the
               stack layout byte-identical regardless of which file was
               spilled, so nothing else here has to know which. */
            if (ins->src.kind == OPND_REG && ins->src.is_float) {
                const char *freg = reg__name(TARGET_X86_64, &ins->src);
                fprintf(out, "    sub rsp, %d\n", stack_slot_size(TARGET_X86_64));
                fprintf(out, "    movsd [rsp], %s\n", freg);
            } else {
                render_simple_operand(TARGET_X86_64, &ins->src, sb, sizeof(sb));
                fprintf(out, "    push %s\n", sb);
            }
            break;

        case OP_POP:
            /* Mirrors OP_PUSH above: a float destination reloads via
               movsd from [rsp] then restores rsp with 'add', instead
               of the GPR-only 'pop'. With no destination the popped
               value still has to land somewhere for an integer pop
               (goes to the scratch register); a float pop with no
               destination isn't a shape wrap_function_body ever
               produces (every float push this function generates always
               has a matching typed pop), so it's not specially handled
               here -- if scratch behavior is ever needed for a bare
               float pop, it would use xmm7/fscratch the same way the
               integer path uses SCRATCH_X86. */
            if (ins->dst.kind == OPND_REG && ins->dst.is_float) {
                const char *freg = reg__name(TARGET_X86_64, &ins->dst);
                fprintf(out, "    movsd %s, [rsp]\n", freg);
                fprintf(out, "    add rsp, %d\n", stack_slot_size(TARGET_X86_64));
            } else {
                fprintf(out, "    pop %s\n", ins->dst.kind == OPND_REG ?
                        reg__name(TARGET_X86_64, &ins->dst) : SCRATCH_X86);
            }
            break;

        case OP_ATOMIC_ADD: case OP_ATOMIC_SUB: {
            /* lock xadd is a true fetch-and-add primitive: it atomically
               adds the source operand into the memory location AND
               returns the location's old value into the source register,
               in one instruction -- no retry loop needed, unlike
               and/or/xor/swap below. OP_ATOMIC_SUB just negates the
               operand first (there's no lock xsub); a negated immediate
               is folded at compile time, a negated register needs one
               extra 'neg' since x86 has no subtract-and-exchange form.
               SRC is guaranteed to be a register or immediate here (see
               the parse-time check), matching lock xadd's own hardware
               requirement that its operand be a register, not memory. */
            int sz = operand_mem_size(&ins->dst);
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : NULL;
            char addr[64];
            x86_addr_text(out, &ins->dst, addr, sizeof(addr));
            const char *valreg = width_reg_name(TARGET_X86_64, &ins->result_reg, sz);
            if (ins->src.kind == OPND_IMM) {
                long v = ins->op == OP_ATOMIC_SUB ? -ins->src.imm : ins->src.imm;
                fprintf(out, "    mov %s, %ld\n", valreg, v);
            } else {
                fprintf(out, "    mov %s, %s\n", valreg, width_reg_name(TARGET_X86_64, &ins->src, sz));
                if (ins->op == OP_ATOMIC_SUB) fprintf(out, "    neg %s\n", valreg);
            }
            if (sizeword) fprintf(out, "    lock xadd %s [%s], %s\n", sizeword, addr, valreg);
            else fprintf(out, "    lock xadd [%s], %s\n", addr, valreg);
            /* result_reg now holds the pre-op value, in place -- xadd's
               whole point is that the source register becomes the old
               value, so no separate 'read the old value' step exists. */
            break;
        }

        case OP_ATOMIC_AND: case OP_ATOMIC_OR: case OP_ATOMIC_XOR: case OP_ATOMIC_SWAP: {
            /* x86-64 has no lock-and/or/xor-and-fetch-old-value form (the
               plain lock and/or/xor instructions modify memory but don't
               report the old value anywhere) -- so these are implemented
               as a compare-and-swap retry loop: read the current value,
               compute the new one, try to CAS it in, retry on failure.
               atom<> needs no computation step (the 'new value' is
               just the operand as-is), so it skips straight to the CAS.
               This costs more than a single instruction under contention,
               but is the only portable way to get a *reported* old value
               out of these three ops on x86-64 without assuming a CPU
               generation newer than plain LOCK-prefix support.

               Register roles, fixed for the whole loop:
                 rax        - cmpxchg's hardware-mandated compare operand
                 resultreg  - holds the freshly-read 'old' value each pass
                              (this is also the value the caller ultimately
                              wants, so no extra copy is needed at the end)
                 SCRATCH_X86 (r14) - the freshly-computed 'new' value passed
                              as cmpxchg's source operand
               SRC is required to already be a register or immediate (see
               the parse-time check in parse_instr_line) precisely because
               this loop only has one free scratch register (r14) to build
               the 'new value' in each pass -- a memory-sourced SRC would
               need a *second*, separate register to survive across r14
               being repeatedly overwritten every retry, which x86-64
               Chard code has no spare for. Matches OP_PUSH's existing
               precedent of rejecting a bare symbol/local operand outright
               instead of silently mishandling it. */
            int sz = operand_mem_size(&ins->dst);
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : NULL;
            char addr[64];
            x86_addr_text(out, &ins->dst, addr, sizeof(addr));
            const char *resultreg = width_reg_name(TARGET_X86_64, &ins->result_reg, sz);
            const char *raxw = sz == 8 ? "rax" : sz == 4 ? "eax" : sz == 2 ? "ax" : "al";
            const char *scratchw = sz == 8 ? SCRATCH_X86 : sz == 4 ? "r14d" : sz == 2 ? "r14w" : "r14b";
            char srcval[32];
            render_simple_operand(TARGET_X86_64, &ins->src, srcval, sizeof(srcval));

            char loop_lbl[32];
            snprintf(loop_lbl, sizeof(loop_lbl), ".Latomic_retry%d", g_label_counter++);

            fprintf(out, "%s:\n", loop_lbl);
            if (sizeword) fprintf(out, "    mov %s, %s [%s]\n", resultreg, sizeword, addr);
            else fprintf(out, "    mov %s, [%s]\n", resultreg, addr);
            fprintf(out, "    mov %s, %s\n", raxw, resultreg); /* cmpxchg's expected-value operand */
            if (ins->op == OP_ATOMIC_SWAP) {
                fprintf(out, "    mov %s, %s\n", scratchw, srcval);
            } else {
                fprintf(out, "    mov %s, %s\n", scratchw, resultreg);
                const char *opname = ins->op == OP_ATOMIC_AND ? "and" : ins->op == OP_ATOMIC_OR ? "or" : "xor";
                fprintf(out, "    %s %s, %s\n", opname, scratchw, srcval);
            }
            if (sizeword) fprintf(out, "    lock cmpxchg %s [%s], %s\n", sizeword, addr, scratchw);
            else fprintf(out, "    lock cmpxchg [%s], %s\n", addr, scratchw);
            fprintf(out, "    jne %s\n", loop_lbl);
            /* resultreg still holds the pre-CAS value read at the top of
               the winning iteration -- correct, since a failed cmpxchg
               means someone else changed the location, so the retry's
               fresh read (not this stale one) becomes the reported old
               value on the next pass, and only a successful pass exits
               the loop with resultreg intact. */
            break;
        }

        case OP_ATOMIC_MAX: case OP_ATOMIC_MIN: {
            /* Same CAS-retry shape as AND/OR/XOR above -- x86-64 has no
               lock-prefixed compare-and-select instruction either, so
               the 'new value' (whichever of the current value / SRC is
               larger, or smaller) is computed with a plain signed
               cmp + cmovg/cmovl against the freshly-read old value,
               then committed the same lock cmpxchg way. See the AND/
               OR/XOR/SWAP case's comment above for the full register-
               role rationale (resultreg/rax/SCRATCH_X86), which applies
               identically here. Signed comparison only, matching the
               opcode_t comment on OP_ATOMIC_MAX/OP_ATOMIC_MIN.

               r15 holds SRC as a second scratch alongside SCRATCH_X86
               (r14) -- the same pair OP_I2S/OP_BCMP already document as
               the two registers never reachable from Chard source, so
               nothing the caller has live can be clobbered by using it
               here too. */
            int sz = operand_mem_size(&ins->dst);
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : NULL;
            char addr[64];
            x86_addr_text(out, &ins->dst, addr, sizeof(addr));
            const char *resultreg = width_reg_name(TARGET_X86_64, &ins->result_reg, sz);
            const char *raxw = sz == 8 ? "rax" : sz == 4 ? "eax" : sz == 2 ? "ax" : "al";
            const char *scratchw = sz == 8 ? SCRATCH_X86 : sz == 4 ? "r14d" : sz == 2 ? "r14w" : "r14b";
            const char *r15w = sz == 8 ? "r15" : sz == 4 ? "r15d" : sz == 2 ? "r15w" : "r15b";
            char srcval[32];
            render_simple_operand(TARGET_X86_64, &ins->src, srcval, sizeof(srcval));

            char loop_lbl[32];
            snprintf(loop_lbl, sizeof(loop_lbl), ".Latomic_retry%d", g_label_counter++);

            fprintf(out, "%s:\n", loop_lbl);
            if (sizeword) fprintf(out, "    mov %s, %s [%s]\n", resultreg, sizeword, addr);
            else fprintf(out, "    mov %s, [%s]\n", resultreg, addr);
            fprintf(out, "    mov %s, %s\n", raxw, resultreg); /* cmpxchg's expected-value operand */
            fprintf(out, "    mov %s, %s\n", r15w, srcval);
            if (sz == 8) {
                fprintf(out, "    cmp %s, %s\n", SCRATCH_X86, r15w);
                fprintf(out, "    mov %s, %s\n", scratchw, resultreg);
                fprintf(out, "    %s %s, %s\n", ins->op == OP_ATOMIC_MAX ? "cmovl" : "cmovg", scratchw, r15w);
            } else {
                /* cmovcc has no useful 8-/16-bit form to lean on, so
                   4-, 2-, and 1-byte locations all compare and select
                   at 32 bits: sign-extend both the old value and SRC
                   into r14d/r15d (so a negative narrow value doesn't
                   compare as a large positive one), select at 32 bits,
                   then the final 'mov scratchw, r14d' truncates back
                   down to the location's actual width before cmpxchg
                   (a no-op truncation when sz == 4). */
                fprintf(out, "    movsx r14d, %s\n", resultreg);
                fprintf(out, "    movsx r15d, %s\n", r15w);
                fprintf(out, "    cmp r14d, r15d\n");
                fprintf(out, "    mov r14d, %s\n", raxw);
                fprintf(out, "    %s r14d, r15d\n", ins->op == OP_ATOMIC_MAX ? "cmovl" : "cmovg");
                fprintf(out, "    mov %s, r14d\n", scratchw);
            }
            if (sizeword) fprintf(out, "    lock cmpxchg %s [%s], %s\n", sizeword, addr, scratchw);
            else fprintf(out, "    lock cmpxchg [%s], %s\n", addr, scratchw);
            fprintf(out, "    jne %s\n", loop_lbl);
            break;
        }

        case OP_ATOMIC_CAS: {
            /* lock cmpxchg's compare operand is hardware-fixed to
               al/ax/eax/rax -- no way to pick a different register,
               same as OP_DIV's idiv. rax is also r1 in Chard's
               numbering, so CAS on a value the caller keeps in r1
               will clobber it -- documented, not silently protected,
               same as idiv's rax/rdx clobber. */
            int sz = operand_mem_size(&ins->dst);
            const char *sizeword = sz == 1 ? "byte" : sz == 2 ? "word" : sz == 4 ? "dword" : NULL;
            char addr[64];
            x86_addr_text(out, &ins->dst, addr, sizeof(addr));
            const char *raxw = sz == 8 ? "rax" : sz == 4 ? "eax" : sz == 2 ? "ax" : "al";
            fprintf(out, "    mov %s, %s\n", raxw, width_reg_name(TARGET_X86_64, &ins->cas_expected, sz));
            if (sizeword) fprintf(out, "    lock cmpxchg %s [%s], %s\n", sizeword, addr, width_reg_name(TARGET_X86_64, &ins->cas_desired, sz));
            else fprintf(out, "    lock cmpxchg [%s], %s\n", addr, reg__name(TARGET_X86_64, &ins->cas_desired));
            /* ZF is set on success (cmpxchg matched); sete gives a clean
               0/1 without a branch. */
            fprintf(out, "    sete %s\n", width_reg_name(TARGET_X86_64, &ins->result_reg, 1));
            fprintf(out, "    movzx %s, %s\n", reg__name(TARGET_X86_64, &ins->result_reg), width_reg_name(TARGET_X86_64, &ins->result_reg, 1));
            break;
        }

        case OP_I2S: {
            /* i2s rSRC > rBUF, rLEN. Digits come from repeated
               div-by-10, least-significant-first, written forward
               starting after any sign byte, then reversed in place --
               no second buffer. idiv is hardware-fixed to rax:rdx
               (same clobber as OP_DIV/OP_ATOMIC_CAS).

               Never reuses rBUF/rLEN/SRC's own registers as scratch:
               since idiv's rax/rdx are hardware-fixed regardless of
               which Chard register aliases them, a caller passing r1
               (rax) or r4 (rdx) as rBUF would corrupt the magnitude
               mid-loop if we treated rBUF as free scratch. Everything
               below uses r14/r15/rax/rdx -- unreachable from Chard
               source -- plus one small stack slot, so no caller
               register choice can collide.

               Register roles:
                 r14 (SCRATCH_X86) - base pointer, copy of rBUF's
                              address, read once up front
                 r15          - running write index during the digit
                              loop, ends holding total byte count;
                              reused as reversal's 'hi' index
                 rax/rdx      - magnitude, then quotient/remainder per
                              division step; free after the digit loop,
                              reused as reversal's lo index (rax) and
                              byte-swap temps (dl/dh)
                 stack (one qword) - holds divisor 10 across the digit
                              loop (idiv reads it as memory, avoiding a
                              fifth register), then a second push/pop
                              spills the digit count across the
                              reversal so r15 is free to become 'hi'

               A leading '-' is written (magnitude negated via NEG,
               correct even for INT64_MIN) before any digits, so the
               reversal never needs to include the sign byte. Presence
               of that sign byte is recovered by peeking rBUF[0]
               after the digit loop rather than threading a start
               index through it. */
            const char *bufreg = reg__name(TARGET_X86_64, &ins->dst);
            const char *lenreg = reg__name(TARGET_X86_64, &ins->len_reg);
            const char *srcreg = reg__name(TARGET_X86_64, &ins->src);

            char id[16];
            snprintf(id, sizeof(id), "%d", g_label_counter++);
            char pos_lbl[40], magready_lbl[40], loop_lbl[40], digitsdone_lbl[40];
            char revbounds_lbl[40], revswap_lbl[40], revcheck_lbl[40];
            snprintf(pos_lbl, sizeof(pos_lbl), ".Li2s_pos%s", id);
            snprintf(magready_lbl, sizeof(magready_lbl), ".Li2s_magready%s", id);
            snprintf(loop_lbl, sizeof(loop_lbl), ".Li2s_loop%s", id);
            snprintf(digitsdone_lbl, sizeof(digitsdone_lbl), ".Li2s_digitsdone%s", id);
            snprintf(revbounds_lbl, sizeof(revbounds_lbl), ".Li2s_revbounds%s", id);
            snprintf(revswap_lbl, sizeof(revswap_lbl), ".Li2s_revswap%s", id);
            snprintf(revcheck_lbl, sizeof(revcheck_lbl), ".Li2s_revcheck%s", id);

            fprintf(out, "    mov %s, %s\n", SCRATCH_X86, bufreg);
            fprintf(out, "    mov rax, %s\n", srcreg);
            fprintf(out, "    cmp rax, 0\n");
            fprintf(out, "    jns %s\n", pos_lbl);
            fprintf(out, "    mov byte [%s], '-'\n", SCRATCH_X86);
            fprintf(out, "    neg rax\n");
            fprintf(out, "    mov r15, 1\n");
            fprintf(out, "    jmp %s\n", magready_lbl);
            fprintf(out, "%s:\n", pos_lbl);
            fprintf(out, "    xor r15, r15\n");
            fprintf(out, "%s:\n", magready_lbl);
            fprintf(out, "    push 10\n"); /* divisor, read as a memory operand below */
            fprintf(out, "    test rax, rax\n");
            fprintf(out, "    jnz %s\n", loop_lbl);
            fprintf(out, "    mov byte [%s + r15], '0'\n", SCRATCH_X86);
            fprintf(out, "    inc r15\n");
            fprintf(out, "    jmp %s\n", digitsdone_lbl);
            fprintf(out, "%s:\n", loop_lbl);
            fprintf(out, "    xor rdx, rdx\n");
            fprintf(out, "    div qword [rsp]\n");
            fprintf(out, "    add dl, '0'\n");
            fprintf(out, "    mov [%s + r15], dl\n", SCRATCH_X86);
            fprintf(out, "    inc r15\n");
            fprintf(out, "    test rax, rax\n");
            fprintf(out, "    jnz %s\n", loop_lbl);
            fprintf(out, "%s:\n", digitsdone_lbl);
            fprintf(out, "    add rsp, 8\n"); /* drop the divisor slot */
            fprintf(out, "    push r15\n"); /* spill the total count */
            /* Peek-based lo: buf[0] is '-' iff the number was negative. */
            fprintf(out, "    xor rax, rax\n");
            fprintf(out, "    cmp byte [%s], '-'\n", SCRATCH_X86);
            fprintf(out, "    jne %s\n", revbounds_lbl);
            fprintf(out, "    mov rax, 1\n");
            fprintf(out, "%s:\n", revbounds_lbl);
            fprintf(out, "    mov r15, [rsp]\n");
            fprintf(out, "    dec r15\n");
            fprintf(out, "    jmp %s\n", revcheck_lbl);
            fprintf(out, "%s:\n", revswap_lbl);
            fprintf(out, "    mov dl, [%s + rax]\n", SCRATCH_X86);
            fprintf(out, "    mov dh, [%s + r15]\n", SCRATCH_X86);
            fprintf(out, "    mov [%s + rax], dh\n", SCRATCH_X86);
            fprintf(out, "    mov [%s + r15], dl\n", SCRATCH_X86);
            fprintf(out, "    inc rax\n");
            fprintf(out, "    dec r15\n");
            fprintf(out, "%s:\n", revcheck_lbl);
            fprintf(out, "    cmp rax, r15\n");
            fprintf(out, "    jl %s\n", revswap_lbl);
            fprintf(out, "    pop %s\n", lenreg); /* retrieves the spilled count as the final answer */
            break;
        }

        case OP_BCMP: {
            /* bcmpN rDST, rPTR1, rPTR2, LEN. rPTR1/rPTR2/LEN are
               read-only inputs; rDST is the one write, touched only via
               a plain 'mov %dstreg, 1' so it is never read back as loop
               state and can safely alias anything (including a loop
               scratch register) without corrupting the count/offset.

               rPTR1/rPTR2/rDST can each be *any* of r1-r12 (rax through
               r13 -- see target_defs[TARGET_X86_64].regs), so unlike a
               case with a handful of fixed hardware-mandated registers
               (e.g. idiv's rax:rdx), there is no register x86-64 offers
               that is guaranteed free except the two genuinely outside
               that r1-r12 mapping: r14 (SCRATCH_X86) and r15. That's
               one fewer than a naive 'offset + countdown + two loaded
               values' plan needs, so this follows i2s's own spill
               pattern: the remaining-length countdown lives in a small
               stack slot (opened and closed within this one
               instruction, symmetric, touching nothing the caller's
               frame relies on) rather than a third register, freeing
               r15 to hold p1's loaded value while p2's side of the
               comparison is read directly as a memory operand ('cmp
               r15, [p2reg + r14]') instead of first loading it into a
               register that doesn't exist to spare.

               Comparison proceeds elem_size bytes at a time (movzx-style
               zero-extended loads, so differing widths never produce a
               false mismatch from stale high bits) for LEN/elem_size
               whole chunks, then a second, separately-looping
               byte-at-a-time pass handles any LEN % elem_size
               remainder -- this keeps the result correct for any LEN
               regardless of whether it happens to be a multiple of
               elem_size, while still doing the documented elem_size-wide
               reads for the common case. Both loops share the same r14
               byte offset (so the tail loop picks up exactly where the
               chunk loop left off) and the same spilled countdown.
               rDST is initialized to 0 (equal) and set to 1 the moment
               any chunk or tail byte differs; once set it is never
               cleared, so a mismatch found early is never undone by a
               later equal chunk. */
            const char *p1reg = reg__name(TARGET_X86_64, &ins->src);
            const char *p2reg = reg__name(TARGET_X86_64, &ins->base_reg);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int sz = ins->elem_size;

            char id[16];
            snprintf(id, sizeof(id), "%d", g_label_counter++);
            char chunk_lbl[40], chunkcheck_lbl[40], chunkskip_lbl[40];
            char tail_lbl[40], tailcheck_lbl[40], tailskip_lbl[40], done_lbl[40];
            snprintf(chunk_lbl, sizeof(chunk_lbl), ".Lbcmp_chunk%s", id);
            snprintf(chunkcheck_lbl, sizeof(chunkcheck_lbl), ".Lbcmp_chunkcheck%s", id);
            snprintf(chunkskip_lbl, sizeof(chunkskip_lbl), ".Lbcmp_chunkskip%s", id);
            snprintf(tail_lbl, sizeof(tail_lbl), ".Lbcmp_tail%s", id);
            snprintf(tailcheck_lbl, sizeof(tailcheck_lbl), ".Lbcmp_tailcheck%s", id);
            snprintf(tailskip_lbl, sizeof(tailskip_lbl), ".Lbcmp_tailskip%s", id);
            snprintf(done_lbl, sizeof(done_lbl), ".Lbcmp_done%s", id);

            fprintf(out, "    xor %s, %s\n", dstreg, dstreg); /* assume equal */
            fprintf(out, "    xor r14, r14\n"); /* byte offset, shared by both loops */
            if (ins->len_reg.kind == OPND_IMM) {
                fprintf(out, "    push %ld\n", ins->len_reg.imm); /* spilled bytes-remaining countdown */
            } else {
                fprintf(out, "    push %s\n", reg__name(TARGET_X86_64, &ins->len_reg));
            }

            /* Chunk loop: elem_size bytes per iteration. Only emitted
               with a real loop body when sz > 1 -- at sz == 1 this is
               identical to the byte tail loop below, so skip straight
               to it rather than emitting the same loop twice. */
            if (sz > 1) {
                fprintf(out, "    jmp %s\n", chunkcheck_lbl);
                fprintf(out, "%s:\n", chunk_lbl);
                if (sz == 2) {
                    fprintf(out, "    movzx r15, word [%s + r14]\n", p1reg);
                    fprintf(out, "    cmp r15w, word [%s + r14]\n", p2reg);
                } else if (sz == 4) {
                    fprintf(out, "    mov r15d, dword [%s + r14]\n", p1reg);
                    fprintf(out, "    cmp r15d, dword [%s + r14]\n", p2reg);
                } else {
                    fprintf(out, "    mov r15, [%s + r14]\n", p1reg);
                    fprintf(out, "    cmp r15, [%s + r14]\n", p2reg);
                }
                fprintf(out, "    je %s\n", chunkskip_lbl); /* skip only the 'set mismatch' store */
                fprintf(out, "    mov %s, 1\n", dstreg);
                fprintf(out, "%s:\n", chunkskip_lbl);
                fprintf(out, "    add r14, %d\n", sz);
                fprintf(out, "    sub qword [rsp], %d\n", sz);
                fprintf(out, "%s:\n", chunkcheck_lbl);
                fprintf(out, "    cmp qword [rsp], %d\n", sz);
                fprintf(out, "    jge %s\n", chunk_lbl);
            }

            /* Byte tail loop: handles sz == 1 in full, or whatever's
               left over (LEN %% elem_size) after the chunk loop above.
               r14 and the spilled countdown already point at the right
               place either way. */
            fprintf(out, "    jmp %s\n", tailcheck_lbl);
            fprintf(out, "%s:\n", tail_lbl);
            fprintf(out, "    movzx r15, byte [%s + r14]\n", p1reg);
            fprintf(out, "    cmp r15b, byte [%s + r14]\n", p2reg);
            fprintf(out, "    je %s\n", tailskip_lbl);
            fprintf(out, "    mov %s, 1\n", dstreg);
            fprintf(out, "%s:\n", tailskip_lbl);
            fprintf(out, "    inc r14\n");
            fprintf(out, "    sub qword [rsp], 1\n");
            fprintf(out, "%s:\n", tailcheck_lbl);
            fprintf(out, "    cmp qword [rsp], 0\n");
            fprintf(out, "    jg %s\n", tail_lbl);
            fprintf(out, "%s:\n", done_lbl);
            fprintf(out, "    add rsp, 8\n"); /* drop the spilled countdown */
            break;
        }

        case OP_BCOPY: {
            /* bcopyN rDST, rSRC, LEN. Both rDST/rSRC are read-only
               pointer inputs (see the OP_BCOPY enum comment on why
               dst is a read here, not a write, and the scan_written_
               registers/pin-checker no-op cases that follow from that).
               Simpler than OP_BCMP immediately above: no result
               register competing for space, so with r14 (SCRATCH_X86)
               holding the shared byte offset, r15 alone is enough to
               stage each chunk's loaded value between the read from
               rSRC and the write to rDST -- no need for bcmpN's
               "read one side into a register, compare the other
               directly as a memory operand" trick, since a copy has
               nothing to compare against. Same spilled-countdown,
               chunked-then-tail two-phase loop shape as bcmpN,
               including the same sz==1 short-circuit (chunk loop
               skipped entirely, tail loop does all the work) -- see
               bcmpN's own comment above for why that's correct. */
            const char *srcreg = reg__name(TARGET_X86_64, &ins->src);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            int sz = ins->elem_size;

            char id[16];
            snprintf(id, sizeof(id), "%d", g_label_counter++);
            char chunk_lbl[40], chunkcheck_lbl[40];
            char tail_lbl[40], tailcheck_lbl[40], done_lbl[40];
            snprintf(chunk_lbl, sizeof(chunk_lbl), ".Lbcopy_chunk%s", id);
            snprintf(chunkcheck_lbl, sizeof(chunkcheck_lbl), ".Lbcopy_chunkcheck%s", id);
            snprintf(tail_lbl, sizeof(tail_lbl), ".Lbcopy_tail%s", id);
            snprintf(tailcheck_lbl, sizeof(tailcheck_lbl), ".Lbcopy_tailcheck%s", id);
            snprintf(done_lbl, sizeof(done_lbl), ".Lbcopy_done%s", id);

            fprintf(out, "    xor r14, r14\n"); /* byte offset, shared by both loops */
            if (ins->len_reg.kind == OPND_IMM) {
                fprintf(out, "    push %ld\n", ins->len_reg.imm); /* spilled bytes-remaining countdown */
            } else {
                fprintf(out, "    push %s\n", reg__name(TARGET_X86_64, &ins->len_reg));
            }

            /* Chunk loop: elem_size bytes per iteration. Same sz > 1
               short-circuit as bcmpN -- at sz == 1 this would be
               identical to the byte tail loop below, so skip straight
               to it instead of emitting the same loop twice. */
            if (sz > 1) {
                fprintf(out, "    jmp %s\n", chunkcheck_lbl);
                fprintf(out, "%s:\n", chunk_lbl);
                if (sz == 2) {
                    fprintf(out, "    movzx r15, word [%s + r14]\n", srcreg);
                    fprintf(out, "    mov word [%s + r14], r15w\n", dstreg);
                } else if (sz == 4) {
                    fprintf(out, "    mov r15d, dword [%s + r14]\n", srcreg);
                    fprintf(out, "    mov dword [%s + r14], r15d\n", dstreg);
                } else {
                    fprintf(out, "    mov r15, [%s + r14]\n", srcreg);
                    fprintf(out, "    mov [%s + r14], r15\n", dstreg);
                }
                fprintf(out, "    add r14, %d\n", sz);
                fprintf(out, "    sub qword [rsp], %d\n", sz);
                fprintf(out, "%s:\n", chunkcheck_lbl);
                fprintf(out, "    cmp qword [rsp], %d\n", sz);
                fprintf(out, "    jge %s\n", chunk_lbl);
            }

            /* Byte tail loop: handles sz == 1 in full, or whatever's
               left over (LEN %% elem_size) after the chunk loop above.
               r14 and the spilled countdown already point at the right
               place either way. */
            fprintf(out, "    jmp %s\n", tailcheck_lbl);
            fprintf(out, "%s:\n", tail_lbl);
            fprintf(out, "    movzx r15, byte [%s + r14]\n", srcreg);
            fprintf(out, "    mov byte [%s + r14], r15b\n", dstreg);
            fprintf(out, "    inc r14\n");
            fprintf(out, "    sub qword [rsp], 1\n");
            fprintf(out, "%s:\n", tailcheck_lbl);
            fprintf(out, "    cmp qword [rsp], 0\n");
            fprintf(out, "    jg %s\n", tail_lbl);
            fprintf(out, "%s:\n", done_lbl);
            fprintf(out, "    add rsp, 8\n"); /* drop the spilled countdown */
            break;
        }

        case OP_S2I: {
            /* s2i rBUF, rLEN > rDST. rBUF/rLEN are read-only inputs
               here (see the pin-check comment on OP_S2I above), so
               unlike i2s their physical registers are never reused as
               scratch -- everything works out of r14/r15 instead,
               which is enough since there's no reversal step to fund
               here, only a single forward accumulate pass.

               The accumulator runs NEGATIVE throughout (dst = dst*10 -
               digit), regardless of the source string's own sign, and
               is only negated back to positive at the very end if the
               string had no leading '-'. Accumulating positively and
               negating at the end (the naive approach) overflows
               int64 by exactly one for "-9223372036854775808"
               (INT64_MIN): its magnitude, 9223372036854775808, does
               not fit in int64_t, so the positive accumulation itself
               would already have wrapped before the final negate ever
               ran. The negative accumulator has no equivalent gap --
               INT64_MIN fits directly with no negation needed, and the
               positive path's own largest possible magnitude,
               INT64_MAX (9223372036854775807), fits equally well
               negated, so 'neg' on that final positive path never
               overflows either. This is the same fix i2s's own
               negative-side handling motivated (see its comment on
               NEG's wraparound), just applied on the parsing side
               instead. */
            const char *bufreg = reg__name(TARGET_X86_64, &ins->dst);
            const char *lenreg = reg__name(TARGET_X86_64, &ins->len_reg);
            const char *dstreg = reg__name(TARGET_X86_64, &ins->result_reg);

            char id[16];
            snprintf(id, sizeof(id), "%d", g_label_counter++);
            char loop_lbl[40], negcheck_lbl[40], done_lbl[40];
            snprintf(loop_lbl, sizeof(loop_lbl), ".Ls2i_loop%s", id);
            snprintf(negcheck_lbl, sizeof(negcheck_lbl), ".Ls2i_negcheck%s", id);
            snprintf(done_lbl, sizeof(done_lbl), ".Ls2i_done%s", id);

            fprintf(out, "    xor %s, %s\n", dstreg, dstreg);
            fprintf(out, "    xor r14, r14\n");
            fprintf(out, "    cmp %s, 0\n", lenreg);
            fprintf(out, "    je %s\n", done_lbl);
            fprintf(out, "    cmp byte [%s], '-'\n", bufreg);
            fprintf(out, "    jne %s\n", loop_lbl);
            fprintf(out, "    mov r14, 1\n");
            fprintf(out, "%s:\n", loop_lbl);
            fprintf(out, "    cmp r14, %s\n", lenreg);
            fprintf(out, "    jge %s\n", negcheck_lbl);
            fprintf(out, "    movzx r15, byte [%s + r14]\n", bufreg);
            fprintf(out, "    sub r15, '0'\n");
            fprintf(out, "    imul %s, %s, 10\n", dstreg, dstreg);
            fprintf(out, "    sub %s, r15\n", dstreg); /* accumulate negatively -- see comment above */
            fprintf(out, "    inc r14\n");
            fprintf(out, "    jmp %s\n", loop_lbl);
            fprintf(out, "%s:\n", negcheck_lbl);
            fprintf(out, "    cmp byte [%s], '-'\n", bufreg);
            fprintf(out, "    je %s\n", done_lbl); /* already negative, and correctly so */
            fprintf(out, "    neg %s\n", dstreg); /* positive path: flip the negative accumulator back */
            fprintf(out, "%s:\n", done_lbl);
            break;
        }

        case OP_RAW:
            /* Emitted verbatim, one leading indent, no further
               processing -- see raw_text's comment on instr_t. */
            fprintf(out, "    %s\n", ins->raw_text);
            break;

        case OP_RAWDATA: {
            /* Anonymous inline data -- same db/dw/dd/dq choice the
               SEC_DATA 'is_data_array' loop above uses for 'data', just
               dropped directly into .text at this point in the
               instruction stream instead of collected up front in
               .data. NASM is happy to mix data directives into .text;
               nothing here marks it non-executable, matching how
               'data'/'volatile' arrays already work today.
               For raw_data_is_float, dsize is only ever 4 or 8 (checked
               at parse time), so dd/dq still cover it -- only the
               per-value formatting differs, going through
               float__bits/double__bits the same way a 'data fK' array's
               initializer list does above, instead of a plain decimal
               literal. */
            const char *dsz = ins->raw_data_size == 1 ? "db" :
                               ins->raw_data_size == 2 ? "dw" :
                               ins->raw_data_size == 4 ? "dd" : "dq";
            fprintf(out, "    %s ", dsz);
            for (int v = 0; v < ins->raw_data_nvals; v++) {
                if (ins->raw_data_is_float) {
                    if (ins->raw_data_size == 4)
                        fprintf(out, "%s0x%08x", v == 0 ? "" : ", ", float__bits(ins->raw_data_fvals[v]));
                    else
                        fprintf(out, "%s0x%016llx", v == 0 ? "" : ", ", (unsigned long long)double__bits(ins->raw_data_fvals[v]));
                } else {
                    /* '&label' entries -- see x86_emit_int_val's comment
                       and the 'bytes' parsing branch's own comment. */
                    x86_emit_int_val(out, ins->raw_data_vals[v], ins->raw_data_val_is_label, ins->raw_data_val_labels, v, v == 0);
                }
            }
            fprintf(out, "\n");
            break;
        }


        case OP_FENCE:
            /* mfence: full store+load barrier, the strongest x86-64
               offers. x86-64's own memory model is already strong enough
               that most fences compilers emit are no-ops in practice --
               but Chard promises sequential consistency across all three
               targets, so this can't be skipped just because x86 rarely
               needs it.

               Weaker orderings: x86-64's memory model already makes
               ordinary loads/stores acquire/release for free (no loads
               are reordered with later loads, no stores with earlier
               stores, and loads aren't reordered with earlier stores to
               a different address), so an acquire, release, or acq_rel
               fence needs no instruction beyond that free ordering --
               matching AArch64/RISC-V's own treatment of a relaxed
               fence as a no-op-but-still-noted request. Only seq_cst
               (the default) needs to additionally block the one
               reordering x86 does still allow -- a later load moving
               ahead of an earlier store -- hence mfence stays reserved
               for that case alone. A relaxed fence establishes no
               ordering by definition and is a no-op on every target. */
            if (ins->mem_order == MEM_ORDER_SEQ_CST)
                fprintf(out, "    mfence\n");
            else if (ins->mem_order == MEM_ORDER_RELAXED)
                fprintf(out, "    // fence %%relaxed -- no ordering requested, no instruction needed\n");
            else
                fprintf(out, "    // fence %s -- free on x86-64's memory model, no instruction needed\n",
                        ins->mem_order == MEM_ORDER_ACQUIRE ? "%acquire" :
                        ins->mem_order == MEM_ORDER_RELEASE ? "%release" : "%acq_rel");
            break;

        /* Floats (SSE2). Every float register (f1-f7 -> xmm0-xmm6, plus
           xmm7 as fscratch) always holds a scalar double in its low 64
           bits -- movsd/addsd/etc operate on that low 64 bits regardless
           of whether the value came from an f32 or f64 memory location,
           matching the "always compute at f64" model described on the
           OP_FADD family above. A float-literal immediate has no SSE
           "move immediate" form (unlike integer mov), so it's
           materialized by loading its raw bit pattern into the integer
           scratch register (SCRATCH_X86) with a plain mov, then moved
           into the destination xmm register with movq -- the standard
           way to get an arbitrary constant into an SSE register without
           a memory round-trip. */
        case OP_FMOV:
            /* f32 (dst.is_f32): movss/32-bit bit pattern via movd.
               f64 (default): movsd/64-bit bit pattern via movq. Same
               xmm register either way (see sregs==fregs comment on
               target_def_t) -- only the mnemonic and immediate width
               change. */
            if (ins->src.kind == OPND_IMM) {
                if (ins->dst.is_f32) {
                    fprintf(out, "    mov %sd, 0x%08x\n", SCRATCH_X86, float__bits(ins->src.fimm));
                    fprintf(out, "    movd %s, %sd\n", reg__name(TARGET_X86_64, &ins->dst), SCRATCH_X86);
                } else {
                    fprintf(out, "    mov %s, 0x%016llx\n", SCRATCH_X86, (unsigned long long)double__bits(ins->src.fimm));
                    fprintf(out, "    movq %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), SCRATCH_X86);
                }
            } else {
                fprintf(out, "    %s %s, %s\n", ins->dst.is_f32 ? "movss" : "movsd",
                        reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            }
            break;

        case OP_FLOAD: {
            /* dst.is_f32 now decides the load width directly -- the
               parse-time check above guarantees sz matches dst's
               register file exactly (4 for an s-register, 8 for an
               f-register), so this is a plain movss/movsd into the
               destination with no widen step at all, unlike the old
               always-widen-to-f64 behavior. */
            char addr[64];
            x86_addr_text(out, &ins->src, addr, sizeof(addr));
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            fprintf(out, "    %s %s, [%s]\n", ins->dst.is_f32 ? "movss" : "movsd", dstreg, addr);
            break;
        }

        case OP_FSTORE: {
            /* Mirrors OP_FLOAD: src.is_f32 decides the store width
               directly, no narrow step -- the parse-time check
               guarantees the destination symbol's declared size
               already matches. */
            char addr[64];
            x86_addr_text(out, &ins->dst, addr, sizeof(addr));
            const char *srcreg = reg__name(TARGET_X86_64, &ins->src);
            fprintf(out, "    %s [%s], %s\n", ins->src.is_f32 ? "movss" : "movsd", addr, srcreg);
            break;
        }

        case OP_VLOAD: {
            /* movupd dst, [addr] -- UNALIGNED 128-bit SSE2 load, not
               movapd. x86_addr_text gives the same base address
               fload/fstore already use (element 0's address is the
               array's base -- see declare_local_array's own comment),
               so no new address computation is needed; the parse-time
               check above already guarantees SYM is a two-element f64
               array (16 real bytes there to read). movupd rather than
               movapd because declare_local_array only guarantees
               8-byte alignment for an f64 array (align = size_bytes,
               i.e. 8, not 16) -- movapd would #GP on a base address
               that isn't 16-byte aligned, which this compiler cannot
               currently promise, so movupd's small constant-factor
               speed cost is the correct trade over an intermittent
               fault. */
            char addr[64];
            x86_addr_text(out, &ins->src, addr, sizeof(addr));
            const char *dstreg = reg__name(TARGET_X86_64, &ins->dst);
            fprintf(out, "    movupd %s, [%s]\n", dstreg, addr);
            break;
        }

        case OP_VSTORE: {
            /* Mirrors OP_VLOAD: movupd (unaligned) rather than movapd,
               same alignment reasoning. */
            char addr[64];
            x86_addr_text(out, &ins->dst, addr, sizeof(addr));
            const char *srcreg = reg__name(TARGET_X86_64, &ins->src);
            fprintf(out, "    movupd [%s], %s\n", addr, srcreg);
            break;
        }

        case OP_FADD: case OP_FSUB: case OP_FMUL: case OP_FDIV: {
            /* dst.is_f32 picks the ss (32-bit) vs sd (64-bit) mnemonic
               variant -- parse-time now guarantees src (if a register)
               is the same file as dst, so no mixed-width case can
               reach here. Immediate materialization mirrors FMOV's
               narrowed path: a 32-bit bit pattern via movd into
               sscratch for f32, the full 64-bit pattern via movq into
               fscratch for f64 (same physical xmm7 either way on
               x86-64, just addressed through the width-appropriate
               name). */
            int f32 = ins->dst.is_f32;
            const char *mn = ins->op == OP_FADD ? (f32 ? "addss" : "addsd") :
                              ins->op == OP_FSUB ? (f32 ? "subss" : "subsd") :
                              ins->op == OP_FMUL ? (f32 ? "mulss" : "mulsd") : (f32 ? "divss" : "divsd");
            if (ins->src.kind == OPND_IMM) {
                if (f32) {
                    fprintf(out, "    mov %sd, 0x%08x\n", SCRATCH_X86, float__bits(ins->src.fimm));
                    fprintf(out, "    movd %s, %sd\n", target_defs[TARGET_X86_64].sscratch, SCRATCH_X86);
                    fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].sscratch);
                } else {
                    fprintf(out, "    mov %s, 0x%016llx\n", SCRATCH_X86, (unsigned long long)double__bits(ins->src.fimm));
                    fprintf(out, "    movq %s, %s\n", target_defs[TARGET_X86_64].fscratch, SCRATCH_X86);
                    fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].fscratch);
                }
            } else {
                fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            }
            break;
        }

        case OP_VADD: case OP_VSUB: case OP_VMUL: case OP_VDIV:
        case OP_VMIN: case OP_VMAX: {
            /* addpd/subpd/mulpd/divpd/minpd/maxpd dst, src -- SSE2
               packed-double arithmetic. Same xmm register reg__name
               already returns for scalar fadd/etc; the pd (packed-
               double) forms just operate on both 64-bit lanes instead
               of the low one, so no operand-rendering changes vs.
               OP_FADD/etc. No immediate-source path -- the parser (see
               the OP_VADD/OP_VSUB/OP_VMUL/OP_VDIV/OP_VMIN/OP_VMAX case
               in the operand-shape switch) already rejects an
               immediate here, so ins->src is always a register. */
            const char *mn = ins->op == OP_VADD ? "addpd" : ins->op == OP_VSUB ? "subpd" :
                              ins->op == OP_VMUL ? "mulpd" : ins->op == OP_VDIV ? "divpd" :
                              ins->op == OP_VMIN ? "minpd" : "maxpd";
            fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            break;
        }

        case OP_VSQRT: {
            /* sqrtpd dst, src -- SSE2 packed-double square root, unary
               like scalar sqrtsd (see OP_FSQRT), just operating on
               both 64-bit lanes instead of the low one only. No
               immediate-source path -- register-only, same as every
               other vN op (see the OP_VSQRT/OP_VABS/OP_VNEG parse-time
               case). */
            fprintf(out, "    sqrtpd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            break;
        }

        case OP_VABS: {
            /* andpd dst, mask -- packed-lane version of OP_FABS's own
               andpd sign-clear idiom (see that case's full rationale;
               the same 0x7fffffffffffffff mask, moved into fscratch via
               movq, works unmodified here because it zero-extends into
               the upper lane the same way every f-register write does
               -- see the OP_VABS opcode_t comment). src is first moved
               into dst if they differ, same reasoning as OP_FABS. Only
               the f64 (andpd) form exists here -- unlike scalar fabs,
               there's no f32 packed variant since the vN family has no
               s-register form at all (see OP_VADD: it's f1-f8 only). */
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src)) != 0)
                fprintf(out, "    movsd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            fprintf(out, "    mov %s, 0x7fffffffffffffff\n", SCRATCH_X86);
            fprintf(out, "    movq %s, %s\n", target_defs[TARGET_X86_64].fscratch, SCRATCH_X86);
            fprintf(out, "    andpd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].fscratch);
            break;
        }

        case OP_VNEG: {
            /* xorpd dst, mask -- packed-lane version of OP_FNEG's own
               xorpd sign-flip idiom (see that case's full rationale;
               same 0x8000000000000000 mask, same zero-extension story
               as OP_VABS above). src is first moved into dst if they
               differ, same reasoning as OP_FNEG. f64-only, same
               f32-has-no-packed-form note as OP_VABS. */
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src)) != 0)
                fprintf(out, "    movsd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            fprintf(out, "    mov %s, 0x8000000000000000\n", SCRATCH_X86);
            fprintf(out, "    movq %s, %s\n", target_defs[TARGET_X86_64].fscratch, SCRATCH_X86);
            fprintf(out, "    xorpd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].fscratch);
            break;
        }

        case OP_VDUP: {
            /* movddup dst, src -- SSE3 "move one double, duplicated":
               reads src's low 64 bits and writes that same value into
               both lanes of dst in one instruction. Dedicated broadcast
               op, no mask/scratch needed (unlike OP_VABS/OP_VNEG above)
               -- src and dst may safely be the same register since
               movddup reads its whole source before writing any part
               of the destination, same in-place safety sqrtpd/etc
               already have. SSE3 rather than baseline SSE2 like the
               rest of the vN family's x86 forms, but every x86-64 CPU
               since 2004 has it, so no feature-detection story is
               needed (see the OP_VDUP opcode_t comment). */
            fprintf(out, "    movddup %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            break;
        }

        case OP_VFMA: {
            /* fDST = fA*fB + fC lane-wise via vfmadd213pd (AVX2+FMA's
               packed-double 213-form -- same destructive-dst, same
               operand-order naming as OP_FMA's own scalar vfmadd213sd,
               just the 'pd' packed variant instead of 'sd'). dst must
               first hold fB (the 213 form's implicit second
               multiplicand), moved in via movapd if fB and dst differ
               -- same move-if-different guard OP_FMA's own case uses,
               just the packed move instruction instead of movsd/movss
               (f64-only here, so no f32 width branch the way OP_FMA
               needs one -- see the OP_VFMA opcode_t comment). fA/fB/fC
               are cas_expected/result_reg/cas_desired respectively,
               same reuse as OP_FMA. */
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg)) != 0)
                fprintf(out, "    movapd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg));
            fprintf(out, "    vfmadd213pd %s, %s, %s\n", reg__name(TARGET_X86_64, &ins->dst),
                    reg__name(TARGET_X86_64, &ins->cas_expected), reg__name(TARGET_X86_64, &ins->cas_desired));
            break;
        }

        case OP_VFMS: {
            /* fDST = fA*fB - fC lane-wise via vfmsub213pd -- OP_VFMA's
               subtract sibling, same destructive-dst 213-form (fB moved
               into dst first if they differ, same move-if-different
               guard), just the 'sub' mnemonic swap. See the OP_VFMS
               opcode_t comment for why AArch64/RISC-V need different
               shaped codegen for this same operation. */
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg)) != 0)
                fprintf(out, "    movapd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg));
            fprintf(out, "    vfmsub213pd %s, %s, %s\n", reg__name(TARGET_X86_64, &ins->dst),
                    reg__name(TARGET_X86_64, &ins->cas_expected), reg__name(TARGET_X86_64, &ins->cas_desired));
            break;
        }

        case OP_VFNMA: {
            /* fDST = fC-(fA*fB) lane-wise via vfnmadd213pd -- OP_VFMA's
               negate sibling, same destructive-dst 213-form (fB moved
               into dst first if they differ, same move-if-different
               guard), just the 'nmadd' mnemonic swap. */
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg)) != 0)
                fprintf(out, "    movapd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg));
            fprintf(out, "    vfnmadd213pd %s, %s, %s\n", reg__name(TARGET_X86_64, &ins->dst),
                    reg__name(TARGET_X86_64, &ins->cas_expected), reg__name(TARGET_X86_64, &ins->cas_desired));
            break;
        }

        case OP_FCMP:
            /* ucomisd dst, src -- same LHS/RHS convention as integer
               OP_CMP (dst is the left/accumulator operand, src is the
               right operand; see OP_CMP's own comment at parse time).
               ucomisd sets ZF/PF/CF the unordered-aware way: PF=1 marks
               a NaN operand, and otherwise ZF/CF read out exactly like
               an unsigned integer compare of dst against src, which is
               why the existing ja/jb/jg/jl family already gives the
               right answer here without any new opcodes. A NaN result
               leaves ZF=0, PF=1, CF=0, which the unsigned jb/ja tests
               read as "not below, not equal" -- i.e. comparing as
               greater, matching the "unordered compares as greater"
               convention from the OP_FCMP comment in the opcode_t
               enum. dst.is_f32 picks ucomiss over ucomisd, same
               width-selection convention as the OP_FADD family above --
               parse-time already guarantees src (if a register) is the
               same width as dst, so no mixed-width case can reach
               here. */
            fprintf(out, "    %s %s, %s\n", ins->dst.is_f32 ? "ucomiss" : "ucomisd", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            break;

        case OP_FSQRT:
            /* sqrtsd: scalar double-precision square root, one
               instruction, no immediate/no-immediate branch needed
               (unary -- src is the whole input, see the parse-time
               comment). Negative input naturally produces NaN, matching
               the opcode_t comment's contract. dst.is_f32 picks sqrtss
               over sqrtsd, same width-selection convention as the
               OP_FADD family -- parse-time already guarantees src (if
               a register) is the same width as dst. */
            fprintf(out, "    %s %s, %s\n", ins->dst.is_f32 ? "sqrtss" : "sqrtsd", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            break;

        case OP_FABS: {
            /* No dedicated scalar fabs instruction on x86-64 SSE2 --
               the standard idiom is and against a mask with every bit
               set except the sign bit, clearing just that bit. For f64
               that's andpd against the 64-bit mask
               0x7fffffffffffffff, moved into fscratch via movq (same
               path as before). For f32 the mask narrows to the 32-bit
               pattern 0x7fffffff, moved into the 32-bit sscratch name
               via movd instead -- movd zeroes the upper 96 bits of the
               destination xmm register (unlike a GPR mov, an SSE
               register-to-register move is never partial), so
               fscratch's upper lanes end up zero either way; using
               movd/sscratch here just keeps the immediate literal
               itself the right width for a 32-bit mask instead of
               sign/zero-extension games on a 64-bit literal. andps
               ANDs all four 32-bit lanes independently, but only lane
               0 (the scalar value) is ever read afterward, so garbage
               in dst's unused upper lanes -- inherited from whatever
               last wrote them -- is harmless regardless of what mask
               width is used. src is first
               moved into dst if they differ, since and(p)s/(p)d is
               destructive (dst &= src) and dst must end up holding the
               source value's bits, not whatever dst previously held --
               movss/movsd picked the same way FMOV narrows its own
               register-to-register copy. */
            int f32 = ins->dst.is_f32;
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src)) != 0)
                fprintf(out, "    %s %s, %s\n", f32 ? "movss" : "movsd", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            if (f32) {
                fprintf(out, "    mov %sd, 0x7fffffff\n", SCRATCH_X86);
                fprintf(out, "    movd %s, %sd\n", target_defs[TARGET_X86_64].sscratch, SCRATCH_X86);
                fprintf(out, "    andps %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].sscratch);
            } else {
                fprintf(out, "    mov %s, 0x7fffffffffffffff\n", SCRATCH_X86);
                fprintf(out, "    movq %s, %s\n", target_defs[TARGET_X86_64].fscratch, SCRATCH_X86);
                fprintf(out, "    andpd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].fscratch);
            }
            break;
        }

        case OP_FNEG: {
            /* No dedicated scalar fneg instruction on x86-64 SSE2,
               same situation as fabs just above -- the standard idiom
               is xor against a mask holding just the sign bit,
               flipping it (vs. fabs's and-against-inverse-mask, which
               clears it). For f64 that's xorpd against
               0x8000000000000000; for f32, xorps against 0x80000000.
               Mask width/movq-vs-movd/scratch-register selection and
               the "move src into dst first if they differ" step are
               identical to OP_FABS's -- see that case's comment above
               for the full rationale, mirrored here with xor in place
               of and and a sign-bit-only mask in place of the
               sign-bit-cleared inverse mask. */
            int f32 = ins->dst.is_f32;
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src)) != 0)
                fprintf(out, "    %s %s, %s\n", f32 ? "movss" : "movsd", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            if (f32) {
                fprintf(out, "    mov %sd, 0x80000000\n", SCRATCH_X86);
                fprintf(out, "    movd %s, %sd\n", target_defs[TARGET_X86_64].sscratch, SCRATCH_X86);
                fprintf(out, "    xorps %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].sscratch);
            } else {
                fprintf(out, "    mov %s, 0x8000000000000000\n", SCRATCH_X86);
                fprintf(out, "    movq %s, %s\n", target_defs[TARGET_X86_64].fscratch, SCRATCH_X86);
                fprintf(out, "    xorpd %s, %s\n", reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].fscratch);
            }
            break;
        }

        case OP_FMIN: case OP_FMAX: {
            /* minsd/maxsd: same destructive dst-OP-src shape as addsd/
               etc above (see that case's comment for the immediate-
               materialization path, mirrored here identically). Both
               instructions already implement the "NaN loses to a real
               operand" convention documented on the OP_FMIN/OP_FMAX
               opcode_t comment -- no extra handling needed to keep that
               consistent with AArch64/RISC-V's own native fmin/fmax.
               dst.is_f32 picks minss/maxss over minsd/maxsd, same
               width-selection convention as the OP_FADD family --
               parse-time already guarantees src (if a register) is the
               same width as dst, so no mixed-width case can reach
               here. */
            int f32 = ins->dst.is_f32;
            const char *mn = ins->op == OP_FMIN ? (f32 ? "minss" : "minsd") : (f32 ? "maxss" : "maxsd");
            if (ins->src.kind == OPND_IMM) {
                if (f32) {
                    fprintf(out, "    mov %sd, 0x%08x\n", SCRATCH_X86, float__bits(ins->src.fimm));
                    fprintf(out, "    movd %s, %sd\n", target_defs[TARGET_X86_64].sscratch, SCRATCH_X86);
                    fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].sscratch);
                } else {
                    fprintf(out, "    mov %s, 0x%016llx\n", SCRATCH_X86, (unsigned long long)double__bits(ins->src.fimm));
                    fprintf(out, "    movq %s, %s\n", target_defs[TARGET_X86_64].fscratch, SCRATCH_X86);
                    fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), target_defs[TARGET_X86_64].fscratch);
                }
            } else {
                fprintf(out, "    %s %s, %s\n", mn, reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            }
            break;
        }

        case OP_FMA: {
            /* fDST = fA*fB + fC via vfmadd213sd (AVX2+FMA form: dst is
               both an input and the output, computing dst = src1*dst +
               src2 in one fused, single-rounding step -- Intel's "213"
               operand-order naming). fA/fB/fC are cas_expected/
               result_reg/cas_desired respectively (see the instr_t
               field comments and the OP_FMA opcode_t comment for why
               those fields are reused here). dst must first hold fB (the
               213 form's implicit second multiplicand), so fB is moved
               into dst before the fused instruction if they're not
               already the same register -- mirroring OP_FABS's own
               move-if-different guard above, for the same reason
               (the instruction is destructive on its dst operand).
               dst.is_f32 picks movss/vfmadd213ss over movsd/
               vfmadd213sd, same width-selection convention as the
               OP_FADD family -- the parser doesn't yet enforce that
               fA/fB/fC/dst all share a width (unlike fadd/etc's
               src-vs-dst check), so this narrows purely off dst as
               documented, matching every other float op's
               width-selection source of truth. */
            int f32 = ins->dst.is_f32;
            if (strcmp(reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg)) != 0)
                fprintf(out, "    %s %s, %s\n", f32 ? "movss" : "movsd", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->result_reg));
            fprintf(out, "    %s %s, %s, %s\n", f32 ? "vfmadd213ss" : "vfmadd213sd", reg__name(TARGET_X86_64, &ins->dst),
                    reg__name(TARGET_X86_64, &ins->cas_expected), reg__name(TARGET_X86_64, &ins->cas_desired));
            break;
        }

        case OP_I2F:
            /* cvtsi2sd/cvtsi2ss -- dst.is_f32 picks the narrow ss form,
               same width-selection convention as the OP_FADD family.
               src is always an integer register/immediate (parse-time
               already guarantees this -- see the OP_I2F parse-time
               check), so there's no mixed-width case to worry about
               here the way FMA's three source operands needed a new
               check: only dst carries a float width at all. */
            if (ins->src.kind == OPND_IMM) {
                fprintf(out, "    mov %s, %ld\n", SCRATCH_X86, ins->src.imm);
                fprintf(out, "    %s %s, %s\n", ins->dst.is_f32 ? "cvtsi2ss" : "cvtsi2sd", reg__name(TARGET_X86_64, &ins->dst), SCRATCH_X86);
            } else {
                fprintf(out, "    %s %s, %s\n", ins->dst.is_f32 ? "cvtsi2ss" : "cvtsi2sd", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            }
            break;

        case OP_F2I:
            /* cvttsd2si/cvttss2si: truncating (toward zero) conversion,
               matching the opcode_t comment's "matching C's (long)x"
               contract -- plain cvtsd2si/cvtss2si would round instead.
               src.is_f32 picks the narrow ss form here, since F2I's
               float operand is src (the mirror image of I2F, whose
               float operand is dst) -- dst is always an integer
               register (parse-time already guarantees this -- see the
               OP_F2I parse-time check), so again no mixed-width case
               to worry about. */
            fprintf(out, "    %s %s, %s\n", ins->src.is_f32 ? "cvttss2si" : "cvttsd2si", reg__name(TARGET_X86_64, &ins->dst), reg__name(TARGET_X86_64, &ins->src));
            break;

        case OP_SYSCALL: {
            /* Linux x86-64 syscall ABI: number in rax, args in
               rdi, rsi, rdx, r10, r8, r9 (in that order). Every arg the
               user actually wrote gets emitted; the rest are left as
               whatever was already in those registers -- Chard does not
               zero unspecified args, since that would be inventing
               state the user didn't ask for. */
            static const char *argregs[6] = {"rdi", "rsi", "rdx", "r10", "r8", "r9"};
            render_simple_operand(TARGET_X86_64, &ins->args[0], sb, sizeof(sb));
            if (is_mem_operand(ins->args[0].kind)) emit_x86_load_scratch(out, &ins->args[0]);
            fprintf(out, "    mov rax, %s\n", is_mem_operand(ins->args[0].kind) ? SCRATCH_X86 : sb);
            for (int a = 1; a < ins->nargs; a++) {
                /* '&SYM' (is_addr_of): the argument wants SYM's address,
                   not the value stored there -- e.g. bind/connect's
                   sockaddr* argument, or sendto/recvfrom's buf and
                   sockaddr* arguments. Same address computation as
                   OP_LEA (x86_addr_text + lea), just landed in this
                   arg's slot register instead of an arbitrary dst. This
                   must be checked before the plain is_mem_operand branch
                   below, since an is_addr_of operand is also
                   is_mem_operand(OPND_SYM) == true and would otherwise
                   fall into the value-load path that motivated this fix
                   in the first place. check_addr_of_violations() (run
                   before codegen) already guarantees is_addr_of can only
                   appear here, never on arg[0] or outside OP_SYSCALL. */
                if ((ins->args[a].kind == OPND_SYM || ins->args[a].kind == OPND_LOCAL) && ins->args[a].is_addr_of) {
                    /* '&local' (is_addr_of on OPND_LOCAL): same
                       materialize-the-address idea as '&SYM' above, just
                       fp-relative. x86_addr_text already emits the
                       frames_up saved-rbp chase (if any) and produces the
                       right 'rbp-N' / 'SCRATCH-N' text for either case,
                       so this is the exact same two lines as the OPND_SYM
                       branch -- no new address computation, just letting
                       an OPND_LOCAL operand reach it via '&'. */
                    char addr[64];
                    x86_addr_text(out, &ins->args[a], addr, sizeof(addr));
                    fprintf(out, "    lea %s, [%s]\n", argregs[a - 1], addr);
                    continue;
                }
                render_simple_operand(TARGET_X86_64, &ins->args[a], sb, sizeof(sb));
                if (is_mem_operand(ins->args[a].kind)) {
                    emit_x86_load_scratch(out, &ins->args[a]);
                    fprintf(out, "    mov %s, %s\n", argregs[a - 1], SCRATCH_X86);
                } else {
                    fprintf(out, "    mov %s, %s\n", argregs[a - 1], sb);
                }
            }
            fprintf(out, "    syscall\n");
            break;
        }

        case OP_READ: case OP_WRITE: {
            /* Named wrappers around read(2)/write(2): same 3-register
               argument shape as OP_SYSCALL (fd, buf, len -> rdi, rsi,
               rdx), just with the syscall number already chosen
               instead of taken from args[0]. Linux x86-64: read = 0,
               write = 1.

               buf (arg 1) is always treated as an address: a symbol or
               local names the buffer to read into / write from, so it
               needs 'lea', not a value load -- matching how out()
               already handles its ascii-string argument. A register
               operand (e.g. a pointer already computed by alloc())
               passes straight through unchanged, since it's already an
               address by the time it reaches here. fd and len are
               ordinary value operands. */
            static const char *argregs3[3] = {"rdi", "rsi", "rdx"};
            fprintf(out, "    mov rax, %d\n", ins->op == OP_READ ? 0 : 1);
            for (int a = 0; a < 3; a++) {
                if (a == 1 && is_mem_operand(ins->args[a].kind)) {
                    char addr[64];
                    x86_addr_text(out, &ins->args[a], addr, sizeof(addr));
                    fprintf(out, "    lea %s, [%s]\n", argregs3[a], addr);
                    continue;
                }
                render_simple_operand(TARGET_X86_64, &ins->args[a], sb, sizeof(sb));
                if (is_mem_operand(ins->args[a].kind)) {
                    emit_x86_load_scratch(out, &ins->args[a]);
                    fprintf(out, "    mov %s, %s\n", argregs3[a], SCRATCH_X86);
                } else {
                    fprintf(out, "    mov %s, %s\n", argregs3[a], sb);
                }
            }
            fprintf(out, "    syscall\n");
            break;
        }

        case OP_LIBC_INIT:
            /* No code to emit here on x86-64: switching entry_label to
               "main" (done once, in emit_x86_64's prologue -- see the
               'global %s'/entry-point setup above) and letting the C
               runtime's own _start do its normal job (argc/argv/envp
               setup, .init_array, etc.) before main() is ever reached
               is the entire story. libc-init's real job is the compile-
               time bookkeeping already done at parse time (g_libc_linked,
               rejecting libcall before it, switching the entry label) --
               nothing needs doing again per-target at the point this
               pseudo-instruction is reached during emission. */
            break;

        case OP_LIBC_CALL: {
            /* SysV AMD64 ABI: integer/pointer args in rdi, rsi, rdx,
               rcx, r8, r9 (in that order) -- NOT the same order
               OP_SYSCALL uses (which substitutes r10 for rcx, since the
               'syscall' instruction itself clobbers rcx/r11). al must
               hold the count of vector (SSE) register arguments for any
               *variadic* callee (printf, scanf, etc.) per the ABI; Chard
               doesn't distinguish variadic from fixed-arity externs, so
               it conservatively always zeroes al -- correct for the
               common case of no float/vararg SSE arguments, and
               harmless for a non-variadic callee (which ignores al
               entirely).

               NOTE on stack alignment: the ABI requires rsp % 16 == 0 at
               the 'call' instruction. Chard's own push/pop and 'call'
               (OP_CALL, for Chard-defined functions) keep this invariant
               implicitly through their own bookkeeping, but libcall does
               not independently verify it -- a libc-init'd program
               using only 'call'/ordinary locals (no manual odd-numbered
               'push') keeps the ABI's alignment naturally, since 'main'
               itself is entered 16-byte aligned and every Chard construct
               that touches rsp does so in aligned pairs (OP_FRAME_OPEN/
               CLOSE) or matched push/pop counts. A program that manually
               pushes an odd number of words before a libcall is
               responsible for its own realignment, the same explicitness
               Chard already expects of manual register-cycle staging at
               ordinary call() sites. */
            static const char *libc_argregs[MAX_LIBC_ARGS] = {"rdi", "rsi", "rdx", "rcx", "r8", "r9"};
            for (int a = 0; a < ins->nargs; a++) {
                if ((ins->args[a].kind == OPND_SYM || ins->args[a].kind == OPND_LOCAL) && ins->args[a].is_addr_of) {
                    char addr[64];
                    x86_addr_text(out, &ins->args[a], addr, sizeof(addr));
                    fprintf(out, "    lea %s, [%s]\n", libc_argregs[a], addr);
                    continue;
                }
                render_simple_operand(TARGET_X86_64, &ins->args[a], sb, sizeof(sb));
                if (is_mem_operand(ins->args[a].kind)) {
                    emit_x86_load_scratch(out, &ins->args[a]);
                    fprintf(out, "    mov %s, %s\n", libc_argregs[a], SCRATCH_X86);
                } else {
                    fprintf(out, "    mov %s, %s\n", libc_argregs[a], sb);
                }
            }
            /* al = 0 vector-register args (see block comment above).
               Deliberately emitted *after* argument marshalling, not
               before: Chard's r1 maps to rax (see target_defs[
               TARGET_X86_64].regs), so any argument sourced from r1
               (an entirely ordinary register to use) would already be
               destroyed by the time it's read if this ran first, as it
               used to -- 'xor eax, eax' zeroing the very register an
               argument might still be waiting to be copied out of. */
            fprintf(out, "    xor eax, eax\n");
            fprintf(out, "    call %s\n", ins->dst.sym);
            if (ins->dst.kind == OPND_REG) {
                /* Return value comes back in rax; move it into the
                   requested r1-r12 slot unless it's already rax
                   (reg_num 1 -- see target_defs[TARGET_X86_64].regs). */
                if (ins->dst.reg_num != 1)
                    fprintf(out, "    mov %s, rax\n", target_defs[TARGET_X86_64].regs[ins->dst.reg_num]);
            }
            break;
        }
        default:
            /* Every opcode this backend doesn't otherwise handle above
               lands here rather than silently emitting nothing. There's
               currently no such opcode reachable at codegen time (every
               value the parser can produce is handled by a case above),
               but this is the safety net if that ever stops being true
               -- e.g. a new opcode added to the enum and wired into one
               backend before the others, which -Wswitch alone won't
               catch unless it happens to be enabled and unless the
               switch has no default (adding this default trades away
               that particular warning for an explicit runtime check
               that fires regardless of build flags). */
            g_source_line = NULL; /* codegen-time: no matching source snippet, see fail_pin_violation */
            fail_fmt("internal error: chard x86-64 backend: unhandled opcode %d", (int)ins->op);
        }
        (void)db;
    }
}

